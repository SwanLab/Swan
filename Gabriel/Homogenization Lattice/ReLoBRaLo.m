classdef ReLoBRaLo < handle

    properties (SetAccess = private, GetAccess = public)
        weightHistory
        lossHistory
        rhoHistory
    end

    properties (Access = private)
        alpha
        temperature
        rhoExpected
        epsilon

        initialized
        stepCount

        initialLoss
        previousLoss

        weights
    end

    methods (Access = public)

        function obj = ReLoBRaLo(cParams)

            obj.init(cParams);

        end

        function weights = update(obj,lossValues)

            lossValues = ...
                lossValues(:);

            obj.validateLossValues(...
                lossValues);

            if ~obj.initialized

                nTerms = ...
                    length(lossValues);

                obj.weights = ...
                    ones(nTerms,1);

                obj.initialLoss = ...
                    lossValues;

                obj.previousLoss = ...
                    lossValues;

                obj.initialized = ...
                    true;

                obj.storeState(...
                    lossValues,...
                    1);

                obj.stepCount = ...
                    1;

                weights = ...
                    obj.weights;

                return

            end

            if length(lossValues) ~= ...
                    length(obj.weights)

                error(...
                    ['Number of loss terms changed ',...
                    'during ReLoBRaLo training.']);

            end

            lambdaPrevious = ...
                obj.computeRelativeWeights(...
                lossValues,...
                obj.previousLoss);

            lambdaInitial = ...
                obj.computeRelativeWeights(...
                lossValues,...
                obj.initialLoss);

            rhoSample = ...
                double(...
                rand < obj.rhoExpected);

            obj.weights = ...
                rhoSample*...
                obj.alpha*...
                obj.weights + ...
                (1-rhoSample)*...
                obj.alpha*...
                lambdaInitial + ...
                (1-obj.alpha)*...
                lambdaPrevious;

            if any(...
                    ~isfinite(obj.weights))

                error(...
                    ['Non-finite ReLoBRaLo ',...
                    'weights were generated.']);

            end

            obj.previousLoss = ...
                lossValues;

            obj.storeState(...
                lossValues,...
                rhoSample);

            obj.stepCount = ...
                obj.stepCount + 1;

            weights = ...
                obj.weights;

        end

        function weights = getWeights(obj)

            weights = ...
                obj.weights;

        end

        function reset(obj)

            obj.initialized = ...
                false;

            obj.stepCount = ...
                0;

            obj.initialLoss = ...
                [];

            obj.previousLoss = ...
                [];

            obj.weights = ...
                [];

            obj.weightHistory = ...
                [];

            obj.lossHistory = ...
                [];

            obj.rhoHistory = ...
                [];

        end

    end

    methods (Access = private)

        function init(obj,cParams)

            requiredFields = {...
                'alpha',...
                'temperature',...
                'rhoExpected'};

            for iField = ...
                    1:length(requiredFields)

                fieldName = ...
                    requiredFields{iField};

                if ~isfield(...
                        cParams,...
                        fieldName)

                    error(...
                        ['Missing ReLoBRaLo ',...
                         'parameter: ',...
                         fieldName]);

                end

            end

            obj.alpha = ...
                cParams.alpha;

            obj.temperature = ...
                cParams.temperature;

            obj.rhoExpected = ...
                cParams.rhoExpected;

            if isfield(...
                    cParams,...
                    'epsilon')

                obj.epsilon = ...
                    cParams.epsilon;

            else

                obj.epsilon = ...
                    1e-12;

            end

            obj.validateParameters();

            obj.initialized = ...
                false;

            obj.stepCount = ...
                0;

            obj.initialLoss = ...
                [];

            obj.previousLoss = ...
                [];

            obj.weights = ...
                [];

            obj.weightHistory = ...
                [];

            obj.lossHistory = ...
                [];

            obj.rhoHistory = ...
                [];

        end

        function validateParameters(obj)

            if ~isscalar(obj.alpha) || ...
                    ~isfinite(obj.alpha) || ...
                    obj.alpha < 0 || ...
                    obj.alpha > 1

                error(...
                    ['ReLoBRaLo alpha must be ',...
                     'between 0 and 1.']);

            end

            if ~isscalar(obj.temperature) || ...
                    ~isfinite(obj.temperature) || ...
                    obj.temperature <= 0

                error(...
                    ['ReLoBRaLo temperature must ',...
                     'be a positive scalar.']);

            end

            if ~isscalar(obj.rhoExpected) || ...
                    ~isfinite(obj.rhoExpected) || ...
                    obj.rhoExpected < 0 || ...
                    obj.rhoExpected > 1

                error(...
                    ['ReLoBRaLo rhoExpected must ',...
                     'be between 0 and 1.']);

            end

            if ~isscalar(obj.epsilon) || ...
                    ~isfinite(obj.epsilon) || ...
                    obj.epsilon <= 0

                error(...
                    ['ReLoBRaLo epsilon must ',...
                     'be a positive scalar.']);

            end

        end

        function validateLossValues(...
                obj,lossValues)

            if isempty(lossValues)

                error(...
                    ['ReLoBRaLo requires at least ',...
                     'one loss term.']);

            end

            if any(...
                    ~isfinite(lossValues))

                error(...
                    ['ReLoBRaLo loss values ',...
                     'must be finite.']);

            end

            if any(...
                    lossValues < 0)

                error(...
                    ['ReLoBRaLo loss values ',...
                     'must be non-negative.']);

            end

        end

        function lambda = ...
                computeRelativeWeights(...
                obj,currentLoss,referenceLoss)

            if length(currentLoss) ~= ...
                    length(referenceLoss)

                error(...
                    ['Current and reference losses ',...
                     'must have the same size.']);

            end

            nTerms = ...
                length(currentLoss);

            denominator = ...
                obj.temperature*...
                referenceLoss + ...
                obj.epsilon;

            z = ...
                currentLoss./...
                denominator;

            if any(...
                    ~isfinite(z))

                error(...
                    ['Non-finite relative losses ',...
                     'detected in ReLoBRaLo.']);

            end

            z = ...
                z - ...
                max(z);

            exponential = ...
                exp(z);

            sumExponential = ...
                sum(exponential);

            if ~isfinite(sumExponential) || ...
                    sumExponential <= 0

                error(...
                    ['Invalid exponential normalization ',...
                     'in ReLoBRaLo.']);

            end

            lambda = ...
                nTerms*...
                exponential/...
                sumExponential;

        end

        function storeState(...
                obj,lossValues,rhoSample)

            obj.lossHistory(:,end+1) = ...
                lossValues;

            obj.weightHistory(:,end+1) = ...
                obj.weights;

            obj.rhoHistory(1,end+1) = ...
                rhoSample;

        end

    end

end