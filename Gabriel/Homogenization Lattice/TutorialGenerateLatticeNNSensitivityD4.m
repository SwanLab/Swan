clc
clear
close all

format long e

fprintf('\n')
fprintf('============================================\n')
fprintf('     GENERATE LATTICE NN D4 SENSITIVITY\n')
fprintf('============================================\n')


%% ------------------------------------------------------------
%  LOAD FEM HOMOGENIZATION DATABASE
% -------------------------------------------------------------

fem = ...
    load(...
    'LatticeHomogenization.mat',...
    'rho',...
    'a',...
    'b',...
    'Chomog');


rho = ...
    fem.rho(:);

a = ...
    fem.a(:);

b = ...
    fem.b(:);

Chomog = ...
    fem.Chomog;


nRho = ...
    length(rho);

nA = ...
    length(a);

nB = ...
    length(b);

nOutputs = ...
    6;


fprintf('\nFEM database loaded\n')

fprintf(...
    'rho points = %d\n',...
    nRho)

fprintf(...
    'a points   = %d\n',...
    nA)

fprintf(...
    'b points   = %d\n',...
    nB)


%% ------------------------------------------------------------
%  CHECK CHOMOG DIMENSIONS
% -------------------------------------------------------------

if size(Chomog,5) ~= nRho || ...
        size(Chomog,6) ~= nA || ...
        size(Chomog,7) ~= nB

    error(...
        'Chomog dimensions do not match rho, a and b.')

end


%% ------------------------------------------------------------
%  CHECK UNIFORM PARAMETER GRIDS
%
%  D4 formulation used here assumes constant spacing.
% -------------------------------------------------------------

dRho = ...
    diff(rho);

dA = ...
    diff(a);

dB = ...
    diff(b);


hRho = ...
    mean(dRho);

hA = ...
    mean(dA);

hB = ...
    mean(dB);


tolGrid = ...
    1e-10;


if max(abs(dRho-hRho)) > ...
        tolGrid*max(1,abs(hRho))

    error(...
        'rho grid is not uniform.')

end


if max(abs(dA-hA)) > ...
        tolGrid*max(1,abs(hA))

    error(...
        'a grid is not uniform.')

end


if max(abs(dB-hB)) > ...
        tolGrid*max(1,abs(hB))

    error(...
        'b grid is not uniform.')

end


fprintf('\nParameter spacing\n')

fprintf(...
    'drho = %.12e\n',...
    hRho)

fprintf(...
    'da   = %.12e\n',...
    hA)

fprintf(...
    'db   = %.12e\n',...
    hB)


%% ------------------------------------------------------------
%  BUILD INDEPENDENT HOMOGENIZED TENSOR COMPONENTS
%
%  C(:,:,:,1) = C1111
%  C(:,:,:,2) = C2222
%  C(:,:,:,3) = C1122
%  C(:,:,:,4) = C1112
%  C(:,:,:,5) = C2212
%  C(:,:,:,6) = C1212
% -------------------------------------------------------------

C = ...
    zeros(...
    nRho,...
    nA,...
    nB,...
    nOutputs);


C(:,:,:,1) = ...
    reshape(...
    Chomog(1,1,1,1,:,:,:),...
    nRho,...
    nA,...
    nB);


C(:,:,:,2) = ...
    reshape(...
    Chomog(2,2,2,2,:,:,:),...
    nRho,...
    nA,...
    nB);


C(:,:,:,3) = ...
    reshape(...
    Chomog(1,1,2,2,:,:,:),...
    nRho,...
    nA,...
    nB);


C(:,:,:,4) = ...
    reshape(...
    Chomog(1,1,1,2,:,:,:),...
    nRho,...
    nA,...
    nB);


C(:,:,:,5) = ...
    reshape(...
    Chomog(2,2,1,2,:,:,:),...
    nRho,...
    nA,...
    nB);


C(:,:,:,6) = ...
    reshape(...
    Chomog(1,2,1,2,:,:,:),...
    nRho,...
    nA,...
    nB);


componentNames = {...
    'C1111',...
    'C2222',...
    'C1122',...
    'C1112',...
    'C2212',...
    'C1212'};


%% ------------------------------------------------------------
%  COMMON D4 INTERIOR DOMAIN
%
%  D4 requires:
%
%      i-2, i-1, i, i+1, i+2
%
%  Therefore two points are removed from each boundary.
% -------------------------------------------------------------

iRho = ...
    3:nRho-2;

iA = ...
    3:nA-2;

iB = ...
    3:nB-2;


rhoInterior = ...
    rho(iRho);

aInterior = ...
    a(iA);

bInterior = ...
    b(iB);


[R,A,B] = ...
    ndgrid(...
    rhoInterior,...
    aInterior,...
    bInterior);


XPhysical = ...
    [...
    R(:),...
    A(:),...
    B(:)];


nSamples = ...
    size(XPhysical,1);


fprintf('\nD4 interior database\n')

fprintf(...
    'Number of samples = %d\n',...
    nSamples)

fprintf(...
    'rho range = [%.12f, %.12f]\n',...
    min(XPhysical(:,1)),...
    max(XPhysical(:,1)))

fprintf(...
    'a range   = [%.12f, %.12f]\n',...
    min(XPhysical(:,2)),...
    max(XPhysical(:,2)))

fprintf(...
    'b range   = [%.12f, %.12f]\n',...
    min(XPhysical(:,3)),...
    max(XPhysical(:,3)))


%% ------------------------------------------------------------
%  FOURTH-ORDER DERIVATIVE WITH RESPECT TO RHO
%
%  D4 f_i =
%
%      -f_(i+2) + 8 f_(i+1)
%      -8 f_(i-1) + f_(i-2)
%      -------------------------
%               12 h
% -------------------------------------------------------------

dCdrho4D = ...
    (...
    -C(iRho+2,iA,iB,:) + ...
     8*C(iRho+1,iA,iB,:) - ...
     8*C(iRho-1,iA,iB,:) + ...
       C(iRho-2,iA,iB,:)...
    )./(12*hRho);


dCdrhoD4 = ...
    reshape(...
    dCdrho4D,...
    nSamples,...
    nOutputs);


%% ------------------------------------------------------------
%  FOURTH-ORDER DERIVATIVE WITH RESPECT TO a
% -------------------------------------------------------------

dCda4D = ...
    (...
    -C(iRho,iA+2,iB,:) + ...
     8*C(iRho,iA+1,iB,:) - ...
     8*C(iRho,iA-1,iB,:) + ...
       C(iRho,iA-2,iB,:)...
    )./(12*hA);


dCdaD4 = ...
    reshape(...
    dCda4D,...
    nSamples,...
    nOutputs);


%% ------------------------------------------------------------
%  FOURTH-ORDER DERIVATIVE WITH RESPECT TO b
% -------------------------------------------------------------

dCdb4D = ...
    (...
    -C(iRho,iA,iB+2,:) + ...
     8*C(iRho,iA,iB+1,:) - ...
     8*C(iRho,iA,iB-1,:) + ...
       C(iRho,iA,iB-2,:)...
    )./(12*hB);


dCdbD4 = ...
    reshape(...
    dCdb4D,...
    nSamples,...
    nOutputs);


%% ------------------------------------------------------------
%  FINITE VALUE CHECK
% -------------------------------------------------------------

if any(~isfinite(XPhysical(:)))

    error(...
        'Non-finite physical inputs detected.')

end


if any(~isfinite(dCdrhoD4(:)))

    error(...
        'Non-finite dC/drho values detected.')

end


if any(~isfinite(dCdaD4(:)))

    error(...
        'Non-finite dC/da values detected.')

end


if any(~isfinite(dCdbD4(:)))

    error(...
        'Non-finite dC/db values detected.')

end


%% ------------------------------------------------------------
%  OPTIONAL D2 REFERENCE ON EXACTLY THE SAME INTERIOR POINTS
%
%  Used only as a diagnostic.
% -------------------------------------------------------------

dCdrho2D = ...
    (...
    C(iRho+1,iA,iB,:) - ...
    C(iRho-1,iA,iB,:)...
    )./(2*hRho);


dCda2D = ...
    (...
    C(iRho,iA+1,iB,:) - ...
    C(iRho,iA-1,iB,:)...
    )./(2*hA);


dCdb2D = ...
    (...
    C(iRho,iA,iB+1,:) - ...
    C(iRho,iA,iB-1,:)...
    )./(2*hB);


dCdrhoD2 = ...
    reshape(...
    dCdrho2D,...
    nSamples,...
    nOutputs);


dCdaD2 = ...
    reshape(...
    dCda2D,...
    nSamples,...
    nOutputs);


dCdbD2 = ...
    reshape(...
    dCdb2D,...
    nSamples,...
    nOutputs);


errorD2D4 = ...
    zeros(3,1);


errorD2D4(1) = ...
    norm(...
    dCdrhoD2-dCdrhoD4,...
    'fro')/...
    max(...
    norm(dCdrhoD4,'fro'),...
    eps);


errorD2D4(2) = ...
    norm(...
    dCdaD2-dCdaD4,...
    'fro')/...
    max(...
    norm(dCdaD4,'fro'),...
    eps);


errorD2D4(3) = ...
    norm(...
    dCdbD2-dCdbD4,...
    'fro')/...
    max(...
    norm(dCdbD4,'fro'),...
    eps);


%% ------------------------------------------------------------
%  BUILD SENSITIVITY DATASET
%
%  Columns:
%
%   1:3     rho, a, b
%
%   4:9     dC/drho
%
%   10:15   dC/da
%
%   16:21   dC/db
% -------------------------------------------------------------

sensitivityData = ...
    [...
    XPhysical,...
    dCdrhoD4,...
    dCdaD4,...
    dCdbD4];


expectedColumns = ...
    3 + ...
    3*nOutputs;


if size(sensitivityData,2) ~= expectedColumns

    error(...
        'Unexpected number of sensitivity columns.')

end


%% ------------------------------------------------------------
%  COLUMN METADATA
% -------------------------------------------------------------

targetColumns.rho = ...
    4:9;

targetColumns.a = ...
    10:15;

targetColumns.b = ...
    16:21;


featureIndex.rho = ...
    1;

featureIndex.a = ...
    2;

featureIndex.b = ...
    3;


columnNames = {...
    'rho',...
    'a',...
    'b',...
    ...
    'dC1111_drho',...
    'dC2222_drho',...
    'dC1122_drho',...
    'dC1112_drho',...
    'dC2212_drho',...
    'dC1212_drho',...
    ...
    'dC1111_da',...
    'dC2222_da',...
    'dC1122_da',...
    'dC1112_da',...
    'dC2212_da',...
    'dC1212_da',...
    ...
    'dC1111_db',...
    'dC2222_db',...
    'dC1122_db',...
    'dC1112_db',...
    'dC2212_db',...
    'dC1212_db'};


%% ------------------------------------------------------------
%  PRINT DERIVATIVE STATISTICS
% -------------------------------------------------------------

fprintf('\n')
fprintf('============================================\n')
fprintf('          D4 DERIVATIVE STATISTICS\n')
fprintf('============================================\n')


derivatives = {...
    dCdrhoD4,...
    dCdaD4,...
    dCdbD4};


variableNames = {...
    'rho',...
    'a',...
    'b'};


for iX = 1:3

    derivativeNorm = ...
        sqrt(...
        sum(...
        derivatives{iX}.^2,...
        2));


    fprintf(...
        '\n%s\n',...
        variableNames{iX})

    fprintf(...
        'Mean norm = %.12e\n',...
        mean(derivativeNorm))

    fprintf(...
        'Max norm  = %.12e\n',...
        max(derivativeNorm))

    fprintf(...
        'D2 vs D4 relative error = %.12e\n',...
        errorD2D4(iX))

end


%% ------------------------------------------------------------
%  SAVE CSV
%
%  No header:
%  SensitivityLossFunctional uses readmatrix.
% -------------------------------------------------------------

csvFileName = ...
    'LatticeNNSensitivityD4.csv';


writematrix(...
    sensitivityData,...
    csvFileName);


%% ------------------------------------------------------------
%  SAVE MAT
% -------------------------------------------------------------

matFileName = ...
    'LatticeNNSensitivityD4.mat';


save(...
    matFileName,...
    'sensitivityData',...
    'XPhysical',...
    'dCdrhoD4',...
    'dCdaD4',...
    'dCdbD4',...
    'dCdrhoD2',...
    'dCdaD2',...
    'dCdbD2',...
    'rhoInterior',...
    'aInterior',...
    'bInterior',...
    'targetColumns',...
    'featureIndex',...
    'componentNames',...
    'columnNames',...
    'errorD2D4',...
    'hRho',...
    'hA',...
    'hB',...
    '-v7.3');


%% ------------------------------------------------------------
%  FINAL CHECK
% -------------------------------------------------------------

fprintf('\n')
fprintf('============================================\n')
fprintf('              FINAL DATA CHECK\n')
fprintf('============================================\n')

fprintf(...
    'Sensitivity dataset = %d x %d\n',...
    size(sensitivityData,1),...
    size(sensitivityData,2))

fprintf(...
    'XPhysical           = %d x %d\n',...
    size(XPhysical,1),...
    size(XPhysical,2))

fprintf(...
    'dC/drho             = %d x %d\n',...
    size(dCdrhoD4,1),...
    size(dCdrhoD4,2))

fprintf(...
    'dC/da               = %d x %d\n',...
    size(dCdaD4,1),...
    size(dCdaD4,2))

fprintf(...
    'dC/db               = %d x %d\n',...
    size(dCdbD4,1),...
    size(dCdbD4,2))


fprintf('\nTarget columns\n')

fprintf(...
    'rho = %d:%d\n',...
    targetColumns.rho(1),...
    targetColumns.rho(end))

fprintf(...
    'a   = %d:%d\n',...
    targetColumns.a(1),...
    targetColumns.a(end))

fprintf(...
    'b   = %d:%d\n',...
    targetColumns.b(1),...
    targetColumns.b(end))


fprintf('\nSaved:\n')
fprintf('  %s\n',csvFileName)
fprintf('  %s\n',matFileName)

fprintf('\n')
fprintf('============================================\n')
fprintf('     D4 SENSITIVITY DATABASE COMPLETED\n')
fprintf('============================================\n')