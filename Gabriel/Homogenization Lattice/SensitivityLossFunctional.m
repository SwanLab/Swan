classdef SensitivityLossFunctional < handle

    properties (Access = private)

        iBatch
        order
        nBatches
        currentBatchIndices
        currentBatchDepleted

    end

    properties (Access = private)

        designVariable
        network
        data

        sensitivityFileName

        variableName
        featureIndex
        targetColumns
        h

        XPhysical

        dCdXPhysical
        dCdX

        XPlus
        XMinus

        denominator

    end


    methods (Access = public)

        function obj = ...
                SensitivityLossFunctional(cParams)

            obj.init(cParams);

            obj.loadSensitivityData();

            obj.prepareData();

            obj.iBatch = ...
                1;

            obj.currentBatchIndices = ...
                [];

            obj.currentBatchDepleted = ...
                false;

            obj.computeNumberOfBatchesAndOrder();

        end


        function [j,dj] = ...
                computeCostAndGradient(obj,x)

            [j,dj] = ...
                obj.computeFunctionAndGradient(x);

        end


        function [j,dj] = ...
                computeFunctionAndGradient(obj,x)

            obj.designVariable.thetavec = ...
                x;

            [j,dj] = ...
                obj.computeSensitivityLoss();

        end


        function [j,dj,isBD] = ...
                computeStochasticCostAndGradient(...
                obj,x,moveBatch)

            obj.designVariable.thetavec = ...
                x;

            obj.updateCurrentBatch(...
                moveBatch);

            indices = ...
                obj.currentBatchIndices;

            [j,dj] = ...
                obj.computeSensitivityLoss(...
                indices);

            % ---------------------------------------------
            % IMPORTANT:
            %
            % SensitivityLossFunctional does not control
            % the end of the SGD epoch.
            %
            % The epoch is controlled by LossFunctional,
            % because the C database has 10500 training
            % samples while sensitivity data has 8736.
            % ---------------------------------------------

            isBD = ...
                false;

        end


        function diagnostics = ...
                computeSensitivityDiagnostics(obj,x)

            obj.designVariable.thetavec = ...
                x;

            % Full sensitivity database

            [...
                j,...
                g,...
                dFd] = ...
                obj.computeSensitivityLoss();


            XNormalized = ...
                obj.data.normalizeInput(...
                obj.XPhysical);


            [~,Janalytic] = ...
                obj.network.computeYOutAndJacobian(...
                XNormalized);


            nOutputs = ...
                size(Janalytic,2);

            nSamples = ...
                size(Janalytic,3);


            dAnalytic = ...
                reshape(...
                Janalytic(...
                obj.featureIndex,:,:),...
                nOutputs,...
                nSamples)';


            diagnostics.name = ...
                obj.variableName;

            diagnostics.featureIndex = ...
                obj.featureIndex;

            diagnostics.j = ...
                j;

            diagnostics.g = ...
                g;

            diagnostics.normG = ...
                norm(g);

            diagnostics.dFd = ...
                dFd;

            diagnostics.dAnalytic = ...
                dAnalytic;


            diagnostics.fdAnalyticError = ...
                norm(...
                dFd-dAnalytic,...
                'fro')/...
                max(...
                norm(dAnalytic,'fro'),...
                eps);


            diagnostics.fdTargetError = ...
                norm(...
                dFd-obj.dCdX,...
                'fro')/...
                max(...
                norm(obj.dCdX,'fro'),...
                eps);


            diagnostics.analyticTargetError = ...
                norm(...
                dAnalytic-obj.dCdX,...
                'fro')/...
                max(...
                norm(obj.dCdX,'fro'),...
                eps);

        end


        function name = ...
                getVariableName(obj)

            name = ...
                obj.variableName;

        end


        function title = ...
                getTitleToPlot(obj)

            title = ...
                ['Sensitivity ',...
                 obj.variableName];

        end

    end


    methods (Access = private)

        function init(obj,cParams)

            requiredFields = {...
                'designVariable',...
                'network',...
                'data',...
                'sensitivityFileName',...
                'variableName',...
                'featureIndex',...
                'targetColumns',...
                'h'};


            for iField = ...
                    1:length(requiredFields)

                fieldName = ...
                    requiredFields{iField};

                if ~isfield(...
                        cParams,...
                        fieldName)

                    error(...
                        ['Missing SensitivityLossFunctional ',...
                         'parameter: ',...
                         fieldName]);

                end

            end


            obj.designVariable = ...
                cParams.designVariable;

            obj.network = ...
                cParams.network;

            obj.data = ...
                cParams.data;

            obj.sensitivityFileName = ...
                cParams.sensitivityFileName;

            obj.variableName = ...
                char(cParams.variableName);

            obj.featureIndex = ...
                cParams.featureIndex;

            obj.targetColumns = ...
                cParams.targetColumns(:)';

            obj.h = ...
                cParams.h;


            nFeatures = ...
                size(...
                obj.data.Xtrain,...
                2);


            if ~isscalar(obj.featureIndex) || ...
                    obj.featureIndex < 1 || ...
                    obj.featureIndex > nFeatures || ...
                    obj.featureIndex ~= floor(obj.featureIndex)

                error(...
                    ['featureIndex must be an integer ',...
                     'between 1 and the number of ',...
                     'input features.']);

            end


            if ~isscalar(obj.h) || ...
                    ~isfinite(obj.h) || ...
                    obj.h <= 0

                error(...
                    'Sensitivity step h must be positive.');

            end


            if isempty(obj.targetColumns)

                error(...
                    'targetColumns cannot be empty.');

            end


            if any(...
                    obj.targetColumns < 1) || ...
                    any(...
                    obj.targetColumns ~= ...
                    floor(obj.targetColumns))

                error(...
                    ['targetColumns must contain ',...
                     'positive integer indices.']);

            end

        end


        function loadSensitivityData(obj)

            sensitivityData = ...
                readmatrix(...
                obj.sensitivityFileName);


            if isempty(sensitivityData)

                error(...
                    'Sensitivity data file is empty.');

            end


            if any(...
                    ~isfinite(...
                    sensitivityData(:)))

                error(...
                    ['Sensitivity data contains ',...
                     'NaN or Inf values.']);

            end


            nFeatures = ...
                size(...
                obj.data.Xtrain,...
                2);

            nOutputs = ...
                size(...
                obj.data.Ytrain,...
                2);

            nColumns = ...
                size(...
                sensitivityData,...
                2);


            if nColumns < nFeatures

                error(...
                    ['Sensitivity data does not contain ',...
                     'enough input columns.']);

            end


            if any(...
                    obj.targetColumns > nColumns)

                error(...
                    ['targetColumns exceeds the number ',...
                     'of columns in sensitivity data.']);

            end


            if length(obj.targetColumns) ~= nOutputs

                error(...
                    ['Number of sensitivity target ',...
                     'columns must match number ',...
                     'of network outputs.']);

            end


            obj.XPhysical = ...
                sensitivityData(...
                :,1:nFeatures);


            obj.dCdXPhysical = ...
                sensitivityData(...
                :,obj.targetColumns);


            if size(obj.XPhysical,1) ~= ...
                    size(obj.dCdXPhysical,1)

                error(...
                    ['Input and sensitivity target ',...
                     'sample counts do not match.']);

            end

        end


        function prepareData(obj)

            obj.dCdX = ...
                obj.data.normalizeDerivative(...
                obj.dCdXPhysical,...
                obj.featureIndex);


            XP = ...
                obj.XPhysical;

            XM = ...
                obj.XPhysical;


            XP(:,obj.featureIndex) = ...
                XP(:,obj.featureIndex) + ...
                obj.h;

            XM(:,obj.featureIndex) = ...
                XM(:,obj.featureIndex) - ...
                obj.h;


            obj.XPlus = ...
                obj.data.normalizeInput(...
                XP);

            obj.XMinus = ...
                obj.data.normalizeInput(...
                XM);


            tolerance = ...
                1e-10;


            if any(...
                    obj.XPlus(...
                    :,obj.featureIndex) > ...
                    1+tolerance) || ...
                    any(...
                    obj.XMinus(...
                    :,obj.featureIndex) < ...
                    -1-tolerance)

                error(...
                    ['Central sensitivity difference for ',...
                     obj.variableName,...
                     ' leaves the physical input range. ',...
                     'Use interior sensitivity points ',...
                     'or a boundary-aware scheme.']);

            end


            obj.denominator = ...
                obj.XPlus(...
                :,obj.featureIndex) - ...
                obj.XMinus(...
                :,obj.featureIndex);


            if any(...
                    abs(obj.denominator) <= eps)

                error(...
                    ['Zero finite-difference denominator ',...
                     'for sensitivity variable ',...
                     obj.variableName,...
                     '.']);

            end

        end


        function [ord,nBatches] = ...
                computeNumberOfBatchesAndOrder(obj)

            nD = ...
                size(...
                obj.XPhysical,...
                1);

            batchSize = ...
                obj.computeBatchSize();

            nBatches = ...
                ceil(...
                nD/batchSize);


            if nBatches == 1 || ...
                    nBatches == 0

                ord = ...
                    1:nD;

                nBatches = ...
                    1;

            else

                ord = ...
                    randperm(...
                    nD,...
                    nD);

            end


            obj.order = ...
                ord;

            obj.nBatches = ...
                nBatches;

        end


        function updateCurrentBatch(...
                obj,moveBatch)

            if moveBatch

                obj.currentBatchIndices = ...
                    obj.computeBatchIndices(...
                    obj.iBatch);


                obj.currentBatchDepleted = ...
                    obj.iBatch == ...
                    obj.nBatches;


                obj.iBatch = ...
                    obj.updateBatchCounter(...
                    obj.iBatch,...
                    true);


            elseif isempty(...
                    obj.currentBatchIndices)

                obj.currentBatchIndices = ...
                    obj.computeBatchIndices(...
                    obj.iBatch);


                obj.currentBatchDepleted = ...
                    obj.iBatch == ...
                    obj.nBatches;

            end

        end


        function indices = ...
                computeBatchIndices(...
                obj,iBatch)

            batchSize = ...
                obj.computeBatchSize();


            iStart = ...
                (iBatch-1)*...
                batchSize + ...
                1;


            iEnd = ...
                min(...
                iBatch*batchSize,...
                size(...
                obj.XPhysical,...
                1));


            indices = ...
                obj.order(...
                iStart:iEnd);

        end


        function iB = ...
                updateBatchCounter(...
                obj,iB,moveBatch)

            if ~moveBatch

                return

            end


            if iB < obj.nBatches

                iB = ...
                    iB + 1;


            elseif iB == obj.nBatches

                iB = ...
                    1;


                nD = ...
                    size(...
                    obj.XPhysical,...
                    1);


                obj.order = ...
                    randperm(...
                    nD);

            end

        end


        function batchSize = ...
                computeBatchSize(obj)

            nD = ...
                size(...
                obj.XPhysical,...
                1);


            if nD > 200

                batchSize = ...
                    200;

            else

                batchSize = ...
                    nD;

            end

        end


        function [j,dj,dFd] = ...
                computeSensitivityLoss(...
                obj,indices)

            % -------------------------------------------------
            % No indices:
            %
            % use the complete sensitivity database.
            %
            % With indices:
            %
            % use only the current stochastic batch.
            % -------------------------------------------------

            if nargin < 2 || ...
                    isempty(indices)

                XPlusLocal = ...
                    obj.XPlus;

                XMinusLocal = ...
                    obj.XMinus;

                denominatorLocal = ...
                    obj.denominator;

                targetLocal = ...
                    obj.dCdX;


            else

                XPlusLocal = ...
                    obj.XPlus(...
                    indices,:);

                XMinusLocal = ...
                    obj.XMinus(...
                    indices,:);

                denominatorLocal = ...
                    obj.denominator(...
                    indices,:);

                targetLocal = ...
                    obj.dCdX(...
                    indices,:);

            end


            YPlus = ...
                obj.network.computeYOut(...
                XPlusLocal);

            YMinus = ...
                obj.network.computeYOut(...
                XMinusLocal);


            dFd = ...
                (YPlus-YMinus)./...
                denominatorLocal;


            error = ...
                dFd-targetLocal;


            j = ...
                0.5*mean(...
                sum(...
                error.^2,...
                2));


            dYPlus = ...
                error./...
                denominatorLocal;

            dYMinus = ...
                -error./...
                denominatorLocal;


            % Network.backprop stores the forward state.
            % Therefore each backprop must be preceded by
            % the corresponding forward evaluation.

            YPlus = ...
                obj.network.computeYOut(...
                XPlusLocal);

            gPlus = ...
                obj.network.backprop(...
                YPlus,...
                dYPlus);


            YMinus = ...
                obj.network.computeYOut(...
                XMinusLocal);

            gMinus = ...
                obj.network.backprop(...
                YMinus,...
                dYMinus);


            dj = ...
                gPlus + ...
                gMinus;

        end

    end

end