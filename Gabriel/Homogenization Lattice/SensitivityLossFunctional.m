classdef SensitivityLossFunctional < handle

    properties (Access = private)
        designVariable
        network
        data
        sensitivityFileName

        XPhysical

        dCdaPhysical
        dCdbPhysical

        dCda
        dCdb

        XaPlus
        XaMinus

        XbPlus
        XbMinus

        denominatorA
        denominatorB

        hA
        hB
    end

    methods (Access = public)

        function obj = SensitivityLossFunctional(cParams)

            obj.init(cParams);

            obj.loadSensitivityData();

            obj.prepareData();

        end

        function [j,dj] = ...
                computeCostAndGradient(obj,x)

            [j,dj] = ...
                obj.computeFunctionAndGradient(x);

        end

        function [j,dj] = ...
                computeFunctionAndGradient(obj,x)

            obj.designVariable.thetavec = x;

            [j,dj] = ...
                obj.computeSensitivityLoss();

        end

        function [j,dj,isBD] = ...
                computeStochasticCostAndGradient(...
                obj,x,moveBatch)

            obj.designVariable.thetavec = x;

            [j,dj] = ...
                obj.computeSensitivityLoss();

            isBD = false;

        end

    end

    methods (Access = private)

        function init(obj,cParams)

            obj.designVariable = ...
                cParams.designVariable;

            obj.network = ...
                cParams.network;

            obj.data = ...
                cParams.data;

            obj.hA = ...
                cParams.hA;

            obj.hB = ...
                cParams.hB;

            obj.sensitivityFileName = ...
                cParams.sensitivityFileName;

        end

        function loadSensitivityData(obj)

            sensitivityData = ...
                readmatrix(...
                obj.sensitivityFileName);

            obj.XPhysical = ...
                sensitivityData(:,1:3);

            obj.dCdaPhysical = ...
                sensitivityData(:,10:15);

            obj.dCdbPhysical = ...
                sensitivityData(:,16:21);

        end

        function prepareData(obj)

            obj.dCda = ...
                obj.data.normalizeDerivative(...
                obj.dCdaPhysical,2);

            obj.dCdb = ...
                obj.data.normalizeDerivative(...
                obj.dCdbPhysical,3);

            XaP = obj.XPhysical;
            XaM = obj.XPhysical;

            XbP = obj.XPhysical;
            XbM = obj.XPhysical;

            XaP(:,2) = ...
                XaP(:,2)+obj.hA;

            XaM(:,2) = ...
                XaM(:,2)-obj.hA;

            XbP(:,3) = ...
                XbP(:,3)+obj.hB;

            XbM(:,3) = ...
                XbM(:,3)-obj.hB;

            obj.XaPlus = ...
                obj.data.normalizeInput(XaP);

            obj.XaMinus = ...
                obj.data.normalizeInput(XaM);

            obj.XbPlus = ...
                obj.data.normalizeInput(XbP);

            obj.XbMinus = ...
                obj.data.normalizeInput(XbM);

            obj.denominatorA = ...
                obj.XaPlus(:,2)-...
                obj.XaMinus(:,2);

            obj.denominatorB = ...
                obj.XbPlus(:,3)-...
                obj.XbMinus(:,3);

        end

        function [j,dj] = ...
                computeSensitivityLoss(obj)

            YAp = ...
                obj.network.computeYOut(...
                obj.XaPlus);

            YAm = ...
                obj.network.computeYOut(...
                obj.XaMinus);

            dAnn = ...
                (YAp-YAm)./...
                obj.denominatorA;

            errorA = ...
                dAnn-obj.dCda;

            YBp = ...
                obj.network.computeYOut(...
                obj.XbPlus);

            YBm = ...
                obj.network.computeYOut(...
                obj.XbMinus);

            dBnn = ...
                (YBp-YBm)./...
                obj.denominatorB;

            errorB = ...
                dBnn-obj.dCdb;

            jA = ...
                0.5*mean(...
                sum(errorA.^2,2));

            jB = ...
                0.5*mean(...
                sum(errorB.^2,2));

            j = ...
                0.5*(jA+jB);

            dYAp = ...
                0.5*errorA./...
                obj.denominatorA;

            dYAm = ...
                -0.5*errorA./...
                obj.denominatorA;

            dYBp = ...
                0.5*errorB./...
                obj.denominatorB;

            dYBm = ...
                -0.5*errorB./...
                obj.denominatorB;

            YAp = ...
                obj.network.computeYOut(...
                obj.XaPlus);

            gAp = ...
                obj.network.backprop(...
                YAp,dYAp);

            YAm = ...
                obj.network.computeYOut(...
                obj.XaMinus);

            gAm = ...
                obj.network.backprop(...
                YAm,dYAm);

            YBp = ...
                obj.network.computeYOut(...
                obj.XbPlus);

            gBp = ...
                obj.network.backprop(...
                YBp,dYBp);

            YBm = ...
                obj.network.computeYOut(...
                obj.XbMinus);

            gBm = ...
                obj.network.backprop(...
                YBm,dYBm);

            dj = ...
                gAp + ...
                gAm + ...
                gBp + ...
                gBm;

        end

    end

end