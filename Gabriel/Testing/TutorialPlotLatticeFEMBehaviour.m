clc
clear
close all

fprintf('\n')
fprintf('============================================\n')
fprintf('        LATTICE FEM BEHAVIOUR CHECK\n')
fprintf('============================================\n')


%% ------------------------------------------------------------
%  LOAD FEM DATABASE
% -------------------------------------------------------------

fem = ...
    load(...
    'LatticeHomogenization.mat',...
    'rho',...
    'a',...
    'b',...
    'Chomog');

rho = ...
    fem.rho(:);

a = ...
    fem.a(:);

b = ...
    fem.b(:);

Chomog = ...
    fem.Chomog;

nRho = ...
    length(rho);

nA = ...
    length(a);

nB = ...
    length(b);

nOutputs = ...
    6;


%% ------------------------------------------------------------
%  BUILD C ARRAY
% -------------------------------------------------------------

C = ...
    zeros(...
    nRho,...
    nA,...
    nB,...
    nOutputs);


C(:,:,:,1) = ...
    reshape(...
    Chomog(1,1,1,1,:,:,:),...
    nRho,nA,nB);

C(:,:,:,2) = ...
    reshape(...
    Chomog(2,2,2,2,:,:,:),...
    nRho,nA,nB);

C(:,:,:,3) = ...
    reshape(...
    Chomog(1,1,2,2,:,:,:),...
    nRho,nA,nB);

C(:,:,:,4) = ...
    reshape(...
    Chomog(1,1,1,2,:,:,:),...
    nRho,nA,nB);

C(:,:,:,5) = ...
    reshape(...
    Chomog(2,2,1,2,:,:,:),...
    nRho,nA,nB);

C(:,:,:,6) = ...
    reshape(...
    Chomog(1,2,1,2,:,:,:),...
    nRho,nA,nB);


componentNames = {...
    'C_{1111}',...
    'C_{2222}',...
    'C_{1122}',...
    'C_{1112}',...
    'C_{2212}',...
    'C_{1212}'};


%% ------------------------------------------------------------
%  SELECT REPRESENTATIVE CENTRAL VALUES
% -------------------------------------------------------------

rhoTarget = ...
    0.5;

aTarget = ...
    0.49;

bTarget = ...
    1.65;


[~,iRho] = ...
    min(...
    abs(rho-rhoTarget));

[~,iA] = ...
    min(...
    abs(a-aTarget));

[~,iB] = ...
    min(...
    abs(b-bTarget));


fprintf('\nCentral slice values\n')

fprintf(...
    'rho = %.12f\n',...
    rho(iRho))

fprintf(...
    'a   = %.12f\n',...
    a(iA))

fprintf(...
    'b   = %.12f\n',...
    b(iB))


%% ============================================================
%  1. C VERSUS RHO
% ============================================================

Crho = ...
    squeeze(...
    C(:,iA,iB,:));


figure

tiledlayout(2,3)

for iC = 1:nOutputs

    nexttile

    plot(...
        rho,...
        Crho(:,iC),...
        'o-',...
        'LineWidth',1.5)

    grid on

    xlabel('\rho')

    ylabel(componentNames{iC})

    title(...
        sprintf(...
        '%s, a=%.3f, b=%.3f',...
        componentNames{iC},...
        a(iA),...
        b(iB)))

end

sgtitle('FEM: C^h versus \rho')


%% ============================================================
%  2. C VERSUS a
% ============================================================

Ca = ...
    squeeze(...
    C(iRho,:,iB,:));


figure

tiledlayout(2,3)

for iC = 1:nOutputs

    nexttile

    plot(...
        a,...
        Ca(:,iC),...
        'o-',...
        'LineWidth',1.5)

    grid on

    xlabel('a')

    ylabel(componentNames{iC})

    title(...
        sprintf(...
        '%s, \\rho=%.3f, b=%.3f',...
        componentNames{iC},...
        rho(iRho),...
        b(iB)))

end

sgtitle('FEM: C^h versus a')


%% ============================================================
%  3. C VERSUS b
% ============================================================

Cb = ...
    squeeze(...
    C(iRho,iA,:,:));


figure

tiledlayout(2,3)

for iC = 1:nOutputs

    nexttile

    plot(...
        b,...
        Cb(:,iC),...
        'o-',...
        'LineWidth',1.5)

    grid on

    xlabel('b')

    ylabel(componentNames{iC})

    title(...
        sprintf(...
        '%s, \\rho=%.3f, a=%.3f',...
        componentNames{iC},...
        rho(iRho),...
        a(iA)))

end

sgtitle('FEM: C^h versus b')


%% ============================================================
%  DERIVATIVES WITH RESPECT TO RHO
% ============================================================

hRho = ...
    mean(diff(rho));


d2Rho = ...
    (...
    Crho(3:end,:) - ...
    Crho(1:end-2,:)...
    )/(2*hRho);


d4Rho = ...
    (...
    -Crho(5:end,:) + ...
    8*Crho(4:end-1,:) - ...
    8*Crho(2:end-3,:) + ...
    Crho(1:end-4,:)...
    )/(12*hRho);


rhoD2 = ...
    rho(2:end-1);

rhoD4 = ...
    rho(3:end-2);


figure

tiledlayout(2,3)

for iC = 1:nOutputs

    nexttile

    plot(...
        rhoD2,...
        d2Rho(:,iC),...
        'o-',...
        'LineWidth',1.2)

    hold on

    plot(...
        rhoD4,...
        d4Rho(:,iC),...
        's--',...
        'LineWidth',1.2)

    grid on

    xlabel('\rho')

    ylabel(...
        ['\partial ',...
         componentNames{iC},...
         '/\partial\rho'])

    title(componentNames{iC})

    legend(...
        'D2',...
        'D4',...
        'Location','best')

end

sgtitle('FEM derivatives: C^h_{,\rho}')


%% ============================================================
%  DERIVATIVES WITH RESPECT TO a
% ============================================================

hA = ...
    mean(diff(a));


d2A = ...
    (...
    Ca(3:end,:) - ...
    Ca(1:end-2,:)...
    )/(2*hA);


d4A = ...
    (...
    -Ca(5:end,:) + ...
    8*Ca(4:end-1,:) - ...
    8*Ca(2:end-3,:) + ...
    Ca(1:end-4,:)...
    )/(12*hA);


aD2 = ...
    a(2:end-1);

aD4 = ...
    a(3:end-2);


figure

tiledlayout(2,3)

for iC = 1:nOutputs

    nexttile

    plot(...
        aD2,...
        d2A(:,iC),...
        'o-',...
        'LineWidth',1.2)

    hold on

    plot(...
        aD4,...
        d4A(:,iC),...
        's--',...
        'LineWidth',1.2)

    grid on

    xlabel('a')

    ylabel(...
        ['\partial ',...
         componentNames{iC},...
         '/\partial a'])

    title(componentNames{iC})

    legend(...
        'D2',...
        'D4',...
        'Location','best')

end

sgtitle('FEM derivatives: C^h_{,a}')


%% ============================================================
%  DERIVATIVES WITH RESPECT TO b
% ============================================================

hB = ...
    mean(diff(b));


d2B = ...
    (...
    Cb(3:end,:) - ...
    Cb(1:end-2,:)...
    )/(2*hB);


d4B = ...
    (...
    -Cb(5:end,:) + ...
    8*Cb(4:end-1,:) - ...
    8*Cb(2:end-3,:) + ...
    Cb(1:end-4,:)...
    )/(12*hB);


bD2 = ...
    b(2:end-1);

bD4 = ...
    b(3:end-2);


figure

tiledlayout(2,3)

for iC = 1:nOutputs

    nexttile

    plot(...
        bD2,...
        d2B(:,iC),...
        'o-',...
        'LineWidth',1.2)

    hold on

    plot(...
        bD4,...
        d4B(:,iC),...
        's--',...
        'LineWidth',1.2)

    grid on

    xlabel('b')

    ylabel(...
        ['\partial ',...
         componentNames{iC},...
         '/\partial b'])

    title(componentNames{iC})

    legend(...
        'D2',...
        'D4',...
        'Location','best')

end

sgtitle('FEM derivatives: C^h_{,b}')


%% ============================================================
%  DERIVATIVE NORMS
% ============================================================

normRhoD2 = ...
    sqrt(...
    sum(...
    d2Rho.^2,...
    2));

normRhoD4 = ...
    sqrt(...
    sum(...
    d4Rho.^2,...
    2));


normAD2 = ...
    sqrt(...
    sum(...
    d2A.^2,...
    2));

normAD4 = ...
    sqrt(...
    sum(...
    d4A.^2,...
    2));


normBD2 = ...
    sqrt(...
    sum(...
    d2B.^2,...
    2));

normBD4 = ...
    sqrt(...
    sum(...
    d4B.^2,...
    2));


figure

plot(...
    rhoD2,...
    normRhoD2,...
    'o-',...
    'LineWidth',1.5)

hold on

plot(...
    rhoD4,...
    normRhoD4,...
    's--',...
    'LineWidth',1.5)

grid on

xlabel('\rho')

ylabel('||C^h_{,\rho}||')

legend(...
    'D2',...
    'D4',...
    'Location','best')

title('FEM derivative magnitude: \rho')


figure

plot(...
    aD2,...
    normAD2,...
    'o-',...
    'LineWidth',1.5)

hold on

plot(...
    aD4,...
    normAD4,...
    's--',...
    'LineWidth',1.5)

grid on

xlabel('a')

ylabel('||C^h_{,a}||')

legend(...
    'D2',...
    'D4',...
    'Location','best')

title('FEM derivative magnitude: a')


figure

plot(...
    bD2,...
    normBD2,...
    'o-',...
    'LineWidth',1.5)

hold on

plot(...
    bD4,...
    normBD4,...
    's--',...
    'LineWidth',1.5)

grid on

xlabel('b')

ylabel('||C^h_{,b}||')

legend(...
    'D2',...
    'D4',...
    'Location','best')

title('FEM derivative magnitude: b')


%% ============================================================
%  GEOMETRIC CONDITIONING OF T
% ============================================================

condA = ...
    zeros(size(a));


for i = 1:length(a)

    ai = ...
        a(i);

    bi = ...
        b(iB);

    k = ...
        1/sqrt(1-ai^2);

    T = ...
        k*[...
        bi, ai/bi;...
        ai*bi, 1/bi];

    condA(i) = ...
        cond(T);

end


condB = ...
    zeros(size(b));


for i = 1:length(b)

    ai = ...
        a(iA);

    bi = ...
        b(i);

    k = ...
        1/sqrt(1-ai^2);

    T = ...
        k*[...
        bi, ai/bi;...
        ai*bi, 1/bi];

    condB(i) = ...
        cond(T);

end


figure

semilogy(...
    a,...
    condA,...
    'o-',...
    'LineWidth',1.5)

grid on

xlabel('a')

ylabel('cond(T)')

title(...
    sprintf(...
    'Geometric conditioning versus a, b=%.3f',...
    b(iB)))


figure

semilogy(...
    b,...
    condB,...
    'o-',...
    'LineWidth',1.5)

grid on

xlabel('b')

ylabel('cond(T)')

title(...
    sprintf(...
    'Geometric conditioning versus b, a=%.3f',...
    a(iA)))


