clc
clear
close all

format long e


%% ============================================================
%  FILES
% =============================================================

modelFile = ...
    'LatticeNN_D4_ReLoBRaLo_100.mat';

femFile = ...
    'LatticeHomogenization.mat';

sensitivityFile = ...
    'LatticeNNSensitivityD4.mat';


%% ============================================================
%  LOAD TRAINED NN
% =============================================================

model = ...
    load(...
    modelFile,...
    'problemNN');


problemNN = ...
    model.problemNN;


%% ============================================================
%  LOAD FEM DATABASE
% =============================================================

fem = ...
    load(...
    femFile,...
    'rho',...
    'a',...
    'b',...
    'Chomog');


rho = ...
    fem.rho(:);

a = ...
    fem.a(:);

b = ...
    fem.b(:);

Chomog = ...
    fem.Chomog;


nRho = ...
    length(rho);

nA = ...
    length(a);

nB = ...
    length(b);

nOutputs = ...
    6;


%% ============================================================
%  BUILD FEM COMPONENT ARRAY
% =============================================================

C = ...
    zeros(...
    nRho,...
    nA,...
    nB,...
    nOutputs);


C(:,:,:,1) = ...
    reshape(...
    Chomog(1,1,1,1,:,:,:),...
    nRho,...
    nA,...
    nB);


C(:,:,:,2) = ...
    reshape(...
    Chomog(2,2,2,2,:,:,:),...
    nRho,...
    nA,...
    nB);


C(:,:,:,3) = ...
    reshape(...
    Chomog(1,1,2,2,:,:,:),...
    nRho,...
    nA,...
    nB);


C(:,:,:,4) = ...
    reshape(...
    Chomog(1,1,1,2,:,:,:),...
    nRho,...
    nA,...
    nB);


C(:,:,:,5) = ...
    reshape(...
    Chomog(2,2,1,2,:,:,:),...
    nRho,...
    nA,...
    nB);


C(:,:,:,6) = ...
    reshape(...
    Chomog(1,2,1,2,:,:,:),...
    nRho,...
    nA,...
    nB);


componentNames = {...
    'C_{1111}',...
    'C_{2222}',...
    'C_{1122}',...
    'C_{1112}',...
    'C_{2212}',...
    'C_{1212}'};


%% ============================================================
%  REPRESENTATIVE SLICE
% =============================================================

rhoTarget = ...
    0.5;

aTarget = ...
    0.49;

bTarget = ...
    1.65;


[~,iRho] = ...
    min(abs(rho-rhoTarget));

[~,iA] = ...
    min(abs(a-aTarget));

[~,iB] = ...
    min(abs(b-bTarget));


rho0 = ...
    rho(iRho);

a0 = ...
    a(iA);

b0 = ...
    b(iB);


fprintf('\n')
fprintf('============================================\n')
fprintf('        REPRESENTATIVE FEM / NN SLICE\n')
fprintf('============================================\n')

fprintf(...
    'rho = %.12f\n',...
    rho0)

fprintf(...
    'a   = %.12f\n',...
    a0)

fprintf(...
    'b   = %.12f\n',...
    b0)


%% ============================================================
%  DENSE NN CURVES
% =============================================================

nPlot = ...
    300;


rhoDense = ...
    linspace(...
    min(rho),...
    max(rho),...
    nPlot)';


aDense = ...
    linspace(...
    min(a),...
    max(a),...
    nPlot)';


bDense = ...
    linspace(...
    min(b),...
    max(b),...
    nPlot)';


Xrho = ...
    [...
    rhoDense,...
    a0*ones(nPlot,1),...
    b0*ones(nPlot,1)];


Xa = ...
    [...
    rho0*ones(nPlot,1),...
    aDense,...
    b0*ones(nPlot,1)];


Xb = ...
    [...
    rho0*ones(nPlot,1),...
    a0*ones(nPlot,1),...
    bDense];


CrhoNN = ...
    problemNN.computeOutputValues(...
    Xrho);


CaNN = ...
    problemNN.computeOutputValues(...
    Xa);


CbNN = ...
    problemNN.computeOutputValues(...
    Xb);


%% ============================================================
%  FEM VALUE SLICES
% =============================================================

CrhoFEM = ...
    squeeze(...
    C(:,iA,iB,:));


CaFEM = ...
    squeeze(...
    C(iRho,:,iB,:));


CbFEM = ...
    squeeze(...
    C(iRho,iA,:,:));


%% ============================================================
%  PLOT C VERSUS RHO
% =============================================================

figure

t = ...
    tiledlayout(...
    2,3,...
    'TileSpacing','Compact');


title(...
    t,...
    sprintf(...
    'C^h versus \\rho, a=%.3f, b=%.3f',...
    a0,...
    b0))


for iC = 1:6

    nexttile

    plot(...
        rhoDense,...
        CrhoNN(:,iC),...
        'LineWidth',1.7)

    hold on

    plot(...
        rho,...
        CrhoFEM(:,iC),...
        'o',...
        'LineWidth',1.2)

    grid on

    xlabel('\rho')

    ylabel(...
        componentNames{iC})

    title(...
        componentNames{iC})

    legend(...
        'NN',...
        'FEM',...
        'Location',...
        'best')

end


%% ============================================================
%  PLOT C VERSUS a
% =============================================================

figure

t = ...
    tiledlayout(...
    2,3,...
    'TileSpacing','Compact');


title(...
    t,...
    sprintf(...
    'C^h versus a, \\rho=%.3f, b=%.3f',...
    rho0,...
    b0))


for iC = 1:6

    nexttile

    plot(...
        aDense,...
        CaNN(:,iC),...
        'LineWidth',1.7)

    hold on

    plot(...
        a,...
        CaFEM(:,iC),...
        'o',...
        'LineWidth',1.2)

    grid on

    xlabel('a')

    ylabel(...
        componentNames{iC})

    title(...
        componentNames{iC})

    legend(...
        'NN',...
        'FEM',...
        'Location',...
        'best')

end


%% ============================================================
%  PLOT C VERSUS b
% =============================================================

figure

t = ...
    tiledlayout(...
    2,3,...
    'TileSpacing','Compact');


title(...
    t,...
    sprintf(...
    'C^h versus b, \\rho=%.3f, a=%.3f',...
    rho0,...
    a0))


for iC = 1:6

    nexttile

    plot(...
        bDense,...
        CbNN(:,iC),...
        'LineWidth',1.7)

    hold on

    plot(...
        b,...
        CbFEM(:,iC),...
        'o',...
        'LineWidth',1.2)

    grid on

    xlabel('b')

    ylabel(...
        componentNames{iC})

    title(...
        componentNames{iC})

    legend(...
        'NN',...
        'FEM',...
        'Location',...
        'best')

end


%% ============================================================
%  LOAD D4 DATABASE
% =============================================================

sens = ...
    load(...
    sensitivityFile,...
    'rhoInterior',...
    'aInterior',...
    'bInterior',...
    'dCdrhoD4',...
    'dCdaD4',...
    'dCdbD4');


rhoInterior = ...
    sens.rhoInterior(:);

aInterior = ...
    sens.aInterior(:);

bInterior = ...
    sens.bInterior(:);


nRhoI = ...
    length(rhoInterior);

nAI = ...
    length(aInterior);

nBI = ...
    length(bInterior);


dCdrho = ...
    reshape(...
    sens.dCdrhoD4,...
    nRhoI,...
    nAI,...
    nBI,...
    6);


dCda = ...
    reshape(...
    sens.dCdaD4,...
    nRhoI,...
    nAI,...
    nBI,...
    6);


dCdb = ...
    reshape(...
    sens.dCdbD4,...
    nRhoI,...
    nAI,...
    nBI,...
    6);


%% ============================================================
%  CLOSEST INTERIOR SLICE
% =============================================================

[~,iRhoI] = ...
    min(...
    abs(...
    rhoInterior-rho0));


[~,iAI] = ...
    min(...
    abs(...
    aInterior-a0));


[~,iBI] = ...
    min(...
    abs(...
    bInterior-b0));


rhoI0 = ...
    rhoInterior(iRhoI);

aI0 = ...
    aInterior(iAI);

bI0 = ...
    bInterior(iBI);


%% ============================================================
%  FEM D4 DERIVATIVE SLICES
% =============================================================

dRhoFEM = ...
    squeeze(...
    dCdrho(...
    :,iAI,iBI,:));


dAFEM = ...
    squeeze(...
    dCda(...
    iRhoI,:,iBI,:));


dBFEM = ...
    squeeze(...
    dCdb(...
    iRhoI,iAI,:,:));


%% ============================================================
%  NN DERIVATIVE CURVES
%
%  Only use the D4 interior range for direct comparison.
% =============================================================

rhoDerivativeDense = ...
    linspace(...
    min(rhoInterior),...
    max(rhoInterior),...
    nPlot)';


aDerivativeDense = ...
    linspace(...
    min(aInterior),...
    max(aInterior),...
    nPlot)';


bDerivativeDense = ...
    linspace(...
    min(bInterior),...
    max(bInterior),...
    nPlot)';


XrhoDerivative = ...
    [...
    rhoDerivativeDense,...
    aI0*ones(nPlot,1),...
    bI0*ones(nPlot,1)];


XaDerivative = ...
    [...
    rhoI0*ones(nPlot,1),...
    aDerivativeDense,...
    bI0*ones(nPlot,1)];


XbDerivative = ...
    [...
    rhoI0*ones(nPlot,1),...
    aI0*ones(nPlot,1),...
    bDerivativeDense];


Jrho = ...
    problemNN.computeGradient(...
    XrhoDerivative);


Ja = ...
    problemNN.computeGradient(...
    XaDerivative);


Jb = ...
    problemNN.computeGradient(...
    XbDerivative);


dRhoNN = ...
    reshape(...
    Jrho(1,:,:),...
    6,...
    nPlot)';


dANN = ...
    reshape(...
    Ja(2,:,:),...
    6,...
    nPlot)';


dBNN = ...
    reshape(...
    Jb(3,:,:),...
    6,...
    nPlot)';


%% ============================================================
%  PLOT dC / drho
% =============================================================

figure

t = ...
    tiledlayout(...
    2,3,...
    'TileSpacing','Compact');


title(...
    t,...
    sprintf(...
    'C^h_{,\\rho}: NN versus FEM D4, a=%.3f, b=%.3f',...
    aI0,...
    bI0))


for iC = 1:6

    nexttile

    plot(...
        rhoDerivativeDense,...
        dRhoNN(:,iC),...
        'LineWidth',1.7)

    hold on

    plot(...
        rhoInterior,...
        dRhoFEM(:,iC),...
        'o',...
        'LineWidth',1.2)

    grid on

    xlabel('\rho')

    ylabel(...
        ['\partial ',...
         componentNames{iC},...
         '/\partial\rho'])

    title(...
        componentNames{iC})

    legend(...
        'NN analytic',...
        'FEM D4',...
        'Location',...
        'best')

end


%% ============================================================
%  PLOT dC / da
% =============================================================

figure

t = ...
    tiledlayout(...
    2,3,...
    'TileSpacing','Compact');


title(...
    t,...
    sprintf(...
    'C^h_{,a}: NN versus FEM D4, \\rho=%.3f, b=%.3f',...
    rhoI0,...
    bI0))


for iC = 1:6

    nexttile

    plot(...
        aDerivativeDense,...
        dANN(:,iC),...
        'LineWidth',1.7)

    hold on

    plot(...
        aInterior,...
        dAFEM(:,iC),...
        'o',...
        'LineWidth',1.2)

    grid on

    xlabel('a')

    ylabel(...
        ['\partial ',...
         componentNames{iC},...
         '/\partial a'])

    title(...
        componentNames{iC})

    legend(...
        'NN analytic',...
        'FEM D4',...
        'Location',...
        'best')

end


%% ============================================================
%  PLOT dC / db
% =============================================================

figure

t = ...
    tiledlayout(...
    2,3,...
    'TileSpacing','Compact');


title(...
    t,...
    sprintf(...
    'C^h_{,b}: NN versus FEM D4, \\rho=%.3f, a=%.3f',...
    rhoI0,...
    aI0))


for iC = 1:6

    nexttile

    plot(...
        bDerivativeDense,...
        dBNN(:,iC),...
        'LineWidth',1.7)

    hold on

    plot(...
        bInterior,...
        dBFEM(:,iC),...
        'o',...
        'LineWidth',1.2)

    grid on

    xlabel('b')

    ylabel(...
        ['\partial ',...
         componentNames{iC},...
         '/\partial b'])

    title(...
        componentNames{iC})

    legend(...
        'NN analytic',...
        'FEM D4',...
        'Location',...
        'best')

end


%% ============================================================
%  FINITE CHECK
% =============================================================

if any(~isfinite(CrhoNN(:))) || ...
        any(~isfinite(CaNN(:))) || ...
        any(~isfinite(CbNN(:)))

    error(...
        'Non-finite NN tensor value detected.')

end


if any(~isfinite(dRhoNN(:))) || ...
        any(~isfinite(dANN(:))) || ...
        any(~isfinite(dBNN(:)))

    error(...
        'Non-finite NN derivative detected.')

end


