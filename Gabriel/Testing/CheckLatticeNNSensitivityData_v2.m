pointRhoMid = [...
    0.5,...
    0.951128089570,...
    2.128773340285];

D_rho_mid = ...
    zeros(3,6);

for i = 1:length(factors)

    h = ...
        factors(i)*hRho;

    rhoP = ...
        pointRhoMid(1)+h;

    rhoM = ...
        pointRhoMid(1)-h;

    CP = ...
        lattice.computeHomogenizationAt(...
        rhoP,...
        pointRhoMid(2),...
        pointRhoMid(3));

    CM = ...
        lattice.computeHomogenizationAt(...
        rhoM,...
        pointRhoMid(2),...
        pointRhoMid(3));

    CP = [...
        CP(1,1,1,1),...
        CP(2,2,2,2),...
        CP(1,1,2,2),...
        CP(1,1,1,2),...
        CP(2,2,1,2),...
        CP(1,2,1,2)];

    CM = [...
        CM(1,1,1,1),...
        CM(2,2,2,2),...
        CM(1,1,2,2),...
        CM(1,1,1,2),...
        CM(2,2,1,2),...
        CM(1,2,1,2)];

    D_rho_mid(i,:) = ...
        (CP-CM)/(2*h);

    fprintf(...
        '\nh = %.12e\n',...
        h)

    disp(...
        D_rho_mid(i,:))

end

diff12 = ...
    norm(...
    D_rho_mid(1,:)-...
    D_rho_mid(2,:));

diff24 = ...
    norm(...
    D_rho_mid(2,:)-...
    D_rho_mid(3,:));

ratio = ...
    diff12/...
    max(diff24,eps);

fprintf('\n')
fprintf(...
    '||D_h - D_h/2||   = %.12e\n',...
    diff12)

fprintf(...
    '||D_h/2-D_h/4||   = %.12e\n',...
    diff24)

fprintf(...
    'difference ratio  = %.12e\n',...
    ratio)