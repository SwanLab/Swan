clc
clear
close all

rng(1)

fprintf('\n')
fprintf('============================================\n')
fprintf('       LATTICE NN FEM DATA GENERATION\n')
fprintf('============================================\n')

%% Parameter ranges

rhoMin = ...
    0;

rhoMax = ...
    1;

aMin = ...
    0;

aMax = ...
    0.98;

bMin = ...
    0.3;

bMax = ...
    3;


%% Value dataset parameters

nRhoValue = ...
    30;

rhoValue = ...
    linspace(...
    rhoMin,...
    rhoMax,...
    nRhoValue);

nGeomTrain = ...
    150;

nGeomTest = ...
    60;

nBoundary = ...
    4;

nGeomLHS = ...
    nGeomTrain - ...
    nBoundary;


%% Sensitivity dataset parameters

nRhoSensitivity = ...
    30;

nGeomSensitivity = ...
    40;

hRelative = ...
    5e-3;

hRho = ...
    hRelative*...
    (rhoMax-rhoMin);

hA = ...
    hRelative*...
    (aMax-aMin);

hB = ...
    hRelative*...
    (bMax-bMin);


%% Training geometry sampling

lhsTrain = ...
    lhsdesign(...
    nGeomLHS,...
    2);

aTrain = ...
    aMin + ...
    lhsTrain(:,1)*...
    (aMax-aMin);

bTrain = ...
    bMin + ...
    lhsTrain(:,2)*...
    (bMax-bMin);

geometryTrainInterior = ...
    [...
    aTrain,...
    bTrain];

geometryBoundary = [...
    aMin,bMin;
    aMin,bMax;
    aMax,bMin;
    aMax,bMax];

geometryTrain = [...
    geometryTrainInterior;
    geometryBoundary];


%% Test geometry sampling

lhsTest = ...
    lhsdesign(...
    nGeomTest,...
    2);

aTest = ...
    aMin + ...
    lhsTest(:,1)*...
    (aMax-aMin);

bTest = ...
    bMin + ...
    lhsTest(:,2)*...
    (bMax-bMin);

geometryTest = ...
    [...
    aTest,...
    bTest];


%% Sensitivity sampling

rhoSensitivityFull = ...
    linspace(...
    rhoMin,...
    rhoMax,...
    nRhoSensitivity+2);

rhoSensitivity = ...
    rhoSensitivityFull(2:end-1);

aSensitivityMin = ...
    aMin + ...
    hA;

aSensitivityMax = ...
    aMax - ...
    hA;

bSensitivityMin = ...
    bMin + ...
    hB;

bSensitivityMax = ...
    bMax - ...
    hB;

lhsSensitivity = ...
    lhsdesign(...
    nGeomSensitivity,...
    2);

aSensitivity = ...
    aSensitivityMin + ...
    lhsSensitivity(:,1)*...
    (aSensitivityMax-aSensitivityMin);

bSensitivity = ...
    bSensitivityMin + ...
    lhsSensitivity(:,2)*...
    (bSensitivityMax-bSensitivityMin);

geometrySensitivity = ...
    [...
    aSensitivity,...
    bSensitivity];


%% Check finite-difference domain

if min(rhoSensitivity)-hRho < rhoMin || ...
        max(rhoSensitivity)+hRho > rhoMax

    error(...
        ['rho sensitivity finite-difference ',...
         'points leave the physical domain.'])

end

if min(aSensitivity)-hA < aMin || ...
        max(aSensitivity)+hA > aMax

    error(...
        ['a sensitivity finite-difference ',...
         'points leave the physical domain.'])

end

if min(bSensitivity)-hB < bMin || ...
        max(bSensitivity)+hB > bMax

    error(...
        ['b sensitivity finite-difference ',...
         'points leave the physical domain.'])

end


%% Summary before FEM computation

fprintf('\nParameter ranges\n')

fprintf(...
    'rho: [%g, %g]\n',...
    rhoMin,...
    rhoMax)

fprintf(...
    'a:   [%g, %g]\n',...
    aMin,...
    aMax)

fprintf(...
    'b:   [%g, %g]\n',...
    bMin,...
    bMax)

fprintf('\nFinite-difference steps\n')

fprintf(...
    'h_rho = %.12e\n',...
    hRho)

fprintf(...
    'h_a   = %.12e\n',...
    hA)

fprintf(...
    'h_b   = %.12e\n',...
    hB)

fprintf('\nValue datasets\n')

fprintf(...
    'rho values:          %d\n',...
    length(rhoValue))

fprintf(...
    'training geometries: %d\n',...
    size(geometryTrain,1))

fprintf(...
    'test geometries:     %d\n',...
    size(geometryTest,1))

fprintf(...
    'training samples:    %d\n',...
    length(rhoValue)*...
    size(geometryTrain,1))

fprintf(...
    'test samples:        %d\n',...
    length(rhoValue)*...
    size(geometryTest,1))

fprintf('\nSensitivity dataset\n')

fprintf(...
    'rho values:             %d\n',...
    length(rhoSensitivity))

fprintf(...
    'sensitivity geometries: %d\n',...
    size(geometrySensitivity,1))

fprintf(...
    'sensitivity samples:    %d\n',...
    length(rhoSensitivity)*...
    size(geometrySensitivity,1))


%% Plot sampling

figure

scatter(...
    geometryTrainInterior(:,1),...
    geometryTrainInterior(:,2),...
    40,...
    'filled')

hold on

scatter(...
    geometryBoundary(:,1),...
    geometryBoundary(:,2),...
    70,...
    'filled')

scatter(...
    geometryTest(:,1),...
    geometryTest(:,2),...
    50)

scatter(...
    geometrySensitivity(:,1),...
    geometrySensitivity(:,2),...
    60)

xlabel('a')
ylabel('b')

legend(...
    'Training LHS',...
    'Training boundary',...
    'Test LHS',...
    'Sensitivity LHS',...
    'Location',...
    'best')

title(...
    'Sampling of lattice geometries')

grid on

xlim([aMin,aMax])
ylim([bMin,bMax])

drawnow


%% FEM object

lattice = ...
    TutorialLatticeNN(false);


%% Training value dataset

fprintf('\n')
fprintf('============================================\n')
fprintf('       COMPUTING TRAINING DATASET\n')
fprintf('============================================\n')

tic

trainDataset = ...
    lattice.computeDataset(...
    rhoValue,...
    geometryTrain);

trainTime = ...
    toc;

fprintf(...
    '\nTraining dataset completed in %.2f s\n',...
    trainTime)


%% Test value dataset

fprintf('\n')
fprintf('============================================\n')
fprintf('         COMPUTING TEST DATASET\n')
fprintf('============================================\n')

tic

testDataset = ...
    lattice.computeDataset(...
    rhoValue,...
    geometryTest);

testTime = ...
    toc;

fprintf(...
    '\nTest dataset completed in %.2f s\n',...
    testTime)


%% Base sensitivity dataset

fprintf('\n')
fprintf('============================================\n')
fprintf('     COMPUTING BASE SENSITIVITY DATA\n')
fprintf('============================================\n')

tic

sensitivityBase = ...
    lattice.computeDataset(...
    rhoSensitivity,...
    geometrySensitivity);

sensitivityBaseTime = ...
    toc;

fprintf(...
    '\nBase sensitivity dataset completed in %.2f s\n',...
    sensitivityBaseTime)


%% rho derivative

fprintf('\n')
fprintf('============================================\n')
fprintf('         COMPUTING dC / dRHO\n')
fprintf('============================================\n')

rhoPlus = ...
    rhoSensitivity + ...
    hRho;

rhoMinus = ...
    rhoSensitivity - ...
    hRho;

tic

sensitivityRhoPlus = ...
    lattice.computeDataset(...
    rhoPlus,...
    geometrySensitivity);

sensitivityRhoMinus = ...
    lattice.computeDataset(...
    rhoMinus,...
    geometrySensitivity);

rhoDerivativeTime = ...
    toc;

dCdrho = ...
    (...
    sensitivityRhoPlus(:,4:9) - ...
    sensitivityRhoMinus(:,4:9)...
    )/...
    (2*hRho);

fprintf(...
    '\ndC/drho completed in %.2f s\n',...
    rhoDerivativeTime)


%% a derivative

fprintf('\n')
fprintf('============================================\n')
fprintf('          COMPUTING dC / da\n')
fprintf('============================================\n')

geometryAPlus = ...
    geometrySensitivity;

geometryAMinus = ...
    geometrySensitivity;

geometryAPlus(:,1) = ...
    geometryAPlus(:,1) + ...
    hA;

geometryAMinus(:,1) = ...
    geometryAMinus(:,1) - ...
    hA;

tic

sensitivityAPlus = ...
    lattice.computeDataset(...
    rhoSensitivity,...
    geometryAPlus);

sensitivityAMinus = ...
    lattice.computeDataset(...
    rhoSensitivity,...
    geometryAMinus);

aDerivativeTime = ...
    toc;

dCda = ...
    (...
    sensitivityAPlus(:,4:9) - ...
    sensitivityAMinus(:,4:9)...
    )/...
    (2*hA);

fprintf(...
    '\ndC/da completed in %.2f s\n',...
    aDerivativeTime)


%% b derivative

fprintf('\n')
fprintf('============================================\n')
fprintf('          COMPUTING dC / db\n')
fprintf('============================================\n')

geometryBPlus = ...
    geometrySensitivity;

geometryBMinus = ...
    geometrySensitivity;

geometryBPlus(:,2) = ...
    geometryBPlus(:,2) + ...
    hB;

geometryBMinus(:,2) = ...
    geometryBMinus(:,2) - ...
    hB;

tic

sensitivityBPlus = ...
    lattice.computeDataset(...
    rhoSensitivity,...
    geometryBPlus);

sensitivityBMinus = ...
    lattice.computeDataset(...
    rhoSensitivity,...
    geometryBMinus);

bDerivativeTime = ...
    toc;

dCdb = ...
    (...
    sensitivityBPlus(:,4:9) - ...
    sensitivityBMinus(:,4:9)...
    )/...
    (2*hB);

fprintf(...
    '\ndC/db completed in %.2f s\n',...
    bDerivativeTime)


%% Assemble final sensitivity dataset

sensitivityDataset = [...
    sensitivityBase(:,1:9),...
    dCdrho,...
    dCda,...
    dCdb];


%% Validate generated data

if any(...
        ~isfinite(...
        trainDataset(:)))

    error(...
        ['Training dataset contains ',...
         'NaN or Inf values.'])

end

if any(...
        ~isfinite(...
        testDataset(:)))

    error(...
        ['Test dataset contains ',...
         'NaN or Inf values.'])

end

if any(...
        ~isfinite(...
        sensitivityDataset(:)))

    error(...
        ['Sensitivity dataset contains ',...
         'NaN or Inf values.'])

end

if size(trainDataset,2) ~= 9

    error(...
        'Training dataset must contain 9 columns.')

end

if size(testDataset,2) ~= 9

    error(...
        'Test dataset must contain 9 columns.')

end

if size(sensitivityDataset,2) ~= 27

    error(...
        ['Sensitivity dataset must ',...
         'contain 27 columns.'])

end


%% File names

trainFileName = ...
    'LatticeNNTrainData_v2.csv';

testFileName = ...
    'LatticeNNTestData_v2.csv';

trainGeometryFileName = ...
    'LatticeNNTrainGeometries_v2.csv';

testGeometryFileName = ...
    'LatticeNNTestGeometries_v2.csv';

sensitivityFileName = ...
    'LatticeNNSensitivityData_v2.csv';

sensitivityGeometryFileName = ...
    'LatticeNNSensitivityGeometries_v2.csv';

sensitivityRhoFileName = ...
    'LatticeNNSensitivityRho_v2.csv';

rawSensitivityFileName = ...
    'LatticeNNSensitivityRaw_v2.mat';

infoFileName = ...
    'LatticeNNFEMDataInfo_v2.mat';


%% Write CSV files

writematrix(...
    trainDataset,...
    trainFileName)

