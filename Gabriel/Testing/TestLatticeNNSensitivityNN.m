clc
clear
close all

load('LatticeNNSoftPlus.mat','T_NN')

data = ...
    readmatrix('LatticeNNSensitivityData.csv');

X = data(:,1:3);

Cfem = data(:,4:9);

dAfem = data(:,10:15);

dBfem = data(:,16:21);

rho = X(:,1);
a = X(:,2);
b = X(:,3);

nSamples = size(X,1);
nOutputs = 6;

[Cnn,Jnn] = ...
    T_NN.computeOutputValuesAndGradient(X);

dAnn = ...
    squeeze(Jnn(2,:,:))';

dBnn = ...
    squeeze(Jnn(3,:,:))';

isInterior = ...
    rho > 1e-12 & ...
    rho < 1-1e-12;

isRho0 = ...
    abs(rho) < 1e-12;

isRho1 = ...
    abs(rho-1) < 1e-12;

fprintf('\n')
fprintf('============================================\n')
fprintf('     NN VS FEM - SENSITIVITY DATASET\n')
fprintf('============================================\n')

fprintf('\nNumber of samples = %d\n',nSamples)

errorC = ...
    norm(Cnn-Cfem,'fro')/...
    max(norm(Cfem,'fro'),eps);

errorA = ...
    norm(...
    dAnn(isInterior,:)-dAfem(isInterior,:),...
    'fro')/...
    max(...
    norm(dAfem(isInterior,:),'fro'),...
    eps);

errorB = ...
    norm(...
    dBnn(isInterior,:)-dBfem(isInterior,:),...
    'fro')/...
    max(...
    norm(dBfem(isInterior,:),'fro'),...
    eps);

fprintf('\nGlobal relative errors\n')
fprintf('C      = %.12e\n',errorC)
fprintf('dC/da  = %.12e\n',errorA)
fprintf('dC/db  = %.12e\n',errorB)

errorComponentsC = ...
    vecnorm(Cnn-Cfem,2,1)./...
    max(vecnorm(Cfem,2,1),eps);

errorComponentsA = ...
    vecnorm(...
    dAnn(isInterior,:)-...
    dAfem(isInterior,:),...
    2,1)./...
    max(...
    vecnorm(dAfem(isInterior,:),2,1),...
    eps);

errorComponentsB = ...
    vecnorm(...
    dBnn(isInterior,:)-...
    dBfem(isInterior,:),...
    2,1)./...
    max(...
    vecnorm(dBfem(isInterior,:),2,1),...
    eps);

fprintf('\n')
fprintf('Relative error per tensor component\n')

fprintf('\nC\n')
fprintf(' C1111       C2222       C1122       C1112       C2212       C1212\n')
disp(errorComponentsC)

fprintf('\ndC/da\n')
fprintf(' C1111       C2222       C1122       C1112       C2212       C1212\n')
disp(errorComponentsA)

fprintf('\ndC/db\n')
fprintf(' C1111       C2222       C1122       C1112       C2212       C1212\n')
disp(errorComponentsB)

normAfem = ...
    vecnorm(dAfem,2,2);

normAnn = ...
    vecnorm(dAnn,2,2);

normBfem = ...
    vecnorm(dBfem,2,2);

normBnn = ...
    vecnorm(dBnn,2,2);

absErrorA = ...
    vecnorm(dAnn-dAfem,2,2);

absErrorB = ...
    vecnorm(dBnn-dBfem,2,2);

relErrorA = ...
    absErrorA./...
    max(normAfem,eps);

relErrorB = ...
    absErrorB./...
    max(normBfem,eps);

relAInterior = ...
    relErrorA(isInterior);

relBInterior = ...
    relErrorB(isInterior);

fprintf('\n')
fprintf('============================================\n')
fprintf('       POINTWISE ERROR STATISTICS\n')
fprintf('============================================\n')

fprintf('\ndC/da\n')
fprintf('mean   = %.12e\n',...
    mean(relAInterior))
fprintf('median = %.12e\n',...
    median(relAInterior))
fprintf('p90    = %.12e\n',...
    prctile(relAInterior,90))
fprintf('max    = %.12e\n',...
    max(relAInterior))

fprintf('\ndC/db\n')
fprintf('mean   = %.12e\n',...
    mean(relBInterior))
fprintf('median = %.12e\n',...
    median(relBInterior))
fprintf('p90    = %.12e\n',...
    prctile(relBInterior,90))
fprintf('max    = %.12e\n',...
    max(relBInterior))

fprintf('\n')
fprintf('============================================\n')
fprintf('             ENDPOINT CHECK\n')
fprintf('============================================\n')

fprintf('\nrho = 0\n')

fprintf(...
    'max ||dC_NN/da|| = %.12e\n',...
    max(normAnn(isRho0)))

fprintf(...
    'max ||dC_NN/db|| = %.12e\n',...
    max(normBnn(isRho0)))

fprintf('\nrho = 1\n')

fprintf(...
    'max ||dC_NN/da|| = %.12e\n',...
    max(normAnn(isRho1)))

fprintf(...
    'max ||dC_NN/db|| = %.12e\n',...
    max(normBnn(isRho1)))

fprintf('\n')
fprintf('============================================\n')
fprintf('      LARGEST FEM dC/db REGIONS\n')
fprintf('============================================\n')

[~,orderB] = ...
    sort(normBfem,'descend');

nShow = 10;

for i = 1:nShow

    id = orderB(i);

    fprintf('\nSample %d\n',id)

    fprintf(...
        'rho = %.6f, a = %.6f, b = %.6f\n',...
        rho(id),...
        a(id),...
        b(id))

    fprintf(...
        '||dC_FEM/db|| = %.12e\n',...
        normBfem(id))

    fprintf(...
        '||dC_NN/db||  = %.12e\n',...
        normBnn(id))

    fprintf(...
        'Absolute error = %.12e\n',...
        absErrorB(id))

    fprintf(...
        'Relative error = %.12e\n',...
        relErrorB(id))

    fprintf('NN\n')
    disp(dBnn(id,:))

    fprintf('FEM\n')
    disp(dBfem(id,:))

end