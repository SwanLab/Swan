clc
clear
close all

fprintf('\n')
fprintf('============================================\n')
fprintf('       LATTICE DERIVATIVE CHECK\n')
fprintf('============================================\n')


%% ------------------------------------------------------------
%  LOAD FEM DATABASE
% -------------------------------------------------------------

fem = ...
    load(...
    'LatticeHomogenization.mat',...
    'rho',...
    'a',...
    'b',...
    'Chomog');

rho = ...
    fem.rho(:);

a = ...
    fem.a(:);

b = ...
    fem.b(:);

Chomog = ...
    fem.Chomog;


nRho = ...
    length(rho);

nA = ...
    length(a);

nB = ...
    length(b);

nOutputs = ...
    6;


fprintf('\nFEM database loaded\n')

fprintf(...
    'rho points = %d\n',...
    nRho)

fprintf(...
    'a points   = %d\n',...
    nA)

fprintf(...
    'b points   = %d\n',...
    nB)


%% ------------------------------------------------------------
%  CHECK UNIFORM GRID
%
%  Fourth-order central differences below assume uniform spacing.
% -------------------------------------------------------------

dRho = ...
    diff(rho);

dA = ...
    diff(a);

dB = ...
    diff(b);


hRho = ...
    mean(dRho);

hA = ...
    mean(dA);

hB = ...
    mean(dB);


tolGrid = ...
    1e-12;


if max(abs(dRho-hRho)) > tolGrid

    error(...
        'rho grid is not uniform.')

end


if max(abs(dA-hA)) > tolGrid

    error(...
        'a grid is not uniform.')

end


if max(abs(dB-hB)) > tolGrid

    error(...
        'b grid is not uniform.')

end


fprintf('\nGrid spacing\n')

fprintf(...
    'drho = %.12e\n',...
    hRho)

fprintf(...
    'da   = %.12e\n',...
    hA)

fprintf(...
    'db   = %.12e\n',...
    hB)


%% ------------------------------------------------------------
%  BUILD CONSTITUTIVE ARRAY
%
%  C(:,:,:,1) = C1111
%  C(:,:,:,2) = C2222
%  C(:,:,:,3) = C1122
%  C(:,:,:,4) = C1112
%  C(:,:,:,5) = C2212
%  C(:,:,:,6) = C1212
% -------------------------------------------------------------

C = ...
    zeros(...
    nRho,...
    nA,...
    nB,...
    nOutputs);


C(:,:,:,1) = ...
    reshape(...
    Chomog(1,1,1,1,:,:,:),...
    nRho,...
    nA,...
    nB);


C(:,:,:,2) = ...
    reshape(...
    Chomog(2,2,2,2,:,:,:),...
    nRho,...
    nA,...
    nB);


C(:,:,:,3) = ...
    reshape(...
    Chomog(1,1,2,2,:,:,:),...
    nRho,...
    nA,...
    nB);


C(:,:,:,4) = ...
    reshape(...
    Chomog(1,1,1,2,:,:,:),...
    nRho,...
    nA,...
    nB);


C(:,:,:,5) = ...
    reshape(...
    Chomog(2,2,1,2,:,:,:),...
    nRho,...
    nA,...
    nB);


C(:,:,:,6) = ...
    reshape(...
    Chomog(1,2,1,2,:,:,:),...
    nRho,...
    nA,...
    nB);


%% ------------------------------------------------------------
%  COMMON INTERIOR GRID
%
%  Fourth-order central difference needs two neighbors
%  on each side.
%
%       i = 3,...,n-2
% -------------------------------------------------------------

iRho = ...
    3:nRho-2;

iA = ...
    3:nA-2;

iB = ...
    3:nB-2;


rhoI = ...
    rho(iRho);

aI = ...
    a(iA);

bI = ...
    b(iB);


[R,A,B] = ...
    ndgrid(...
    rhoI,...
    aI,...
    bI);


XCenter = ...
    [...
    R(:),...
    A(:),...
    B(:)];


nSamples = ...
    size(XCenter,1);


fprintf('\nCommon interior points = %d\n',...
    nSamples)


%% ------------------------------------------------------------
%  SECOND-ORDER CENTRAL DIFFERENCES
%
%          f(i+1) - f(i-1)
%  f' ~= -------------------
%                  2 h
% -------------------------------------------------------------

d2Rho4D = ...
    (...
    C(iRho+1,iA,iB,:) - ...
    C(iRho-1,iA,iB,:)...
    )/(2*hRho);


d2A4D = ...
    (...
    C(iRho,iA+1,iB,:) - ...
    C(iRho,iA-1,iB,:)...
    )/(2*hA);


d2B4D = ...
    (...
    C(iRho,iA,iB+1,:) - ...
    C(iRho,iA,iB-1,:)...
    )/(2*hB);


d2Rho = ...
    reshape(...
    d2Rho4D,...
    nSamples,...
    nOutputs);


d2A = ...
    reshape(...
    d2A4D,...
    nSamples,...
    nOutputs);


d2B = ...
    reshape(...
    d2B4D,...
    nSamples,...
    nOutputs);


%% ------------------------------------------------------------
%  FOURTH-ORDER CENTRAL DIFFERENCES
%
%            -f(i+2) + 8f(i+1) - 8f(i-1) + f(i-2)
%  f' ~=    -----------------------------------------
%                              12 h
% -------------------------------------------------------------

d4Rho4D = ...
    (...
    -C(iRho+2,iA,iB,:) + ...
    8*C(iRho+1,iA,iB,:) - ...
    8*C(iRho-1,iA,iB,:) + ...
    C(iRho-2,iA,iB,:)...
    )/(12*hRho);


d4A4D = ...
    (...
    -C(iRho,iA+2,iB,:) + ...
    8*C(iRho,iA+1,iB,:) - ...
    8*C(iRho,iA-1,iB,:) + ...
    C(iRho,iA-2,iB,:)...
    )/(12*hA);


d4B4D = ...
    (...
    -C(iRho,iA,iB+2,:) + ...
    8*C(iRho,iA,iB+1,:) - ...
    8*C(iRho,iA,iB-1,:) + ...
    C(iRho,iA,iB-2,:)...
    )/(12*hB);


d4Rho = ...
    reshape(...
    d4Rho4D,...
    nSamples,...
    nOutputs);


d4A = ...
    reshape(...
    d4A4D,...
    nSamples,...
    nOutputs);


d4B = ...
    reshape(...
    d4B4D,...
    nSamples,...
    nOutputs);


%% ------------------------------------------------------------
%  SECOND ORDER VS FOURTH ORDER
% -------------------------------------------------------------

variableNames = {...
    'rho',...
    'a',...
    'b'};


d2 = {...
    d2Rho,...
    d2A,...
    d2B};


d4 = {...
    d4Rho,...
    d4A,...
    d4B};


errorD2D4 = ...
    zeros(3,1);

rmseD2D4 = ...
    zeros(3,1);


fprintf('\n')
fprintf('============================================\n')
fprintf('       FEM: SECOND VS FOURTH ORDER\n')
fprintf('============================================\n')


for iX = 1:3

    diffDerivative = ...
        d2{iX} - ...
        d4{iX};


    errorD2D4(iX) = ...
        norm(...
        diffDerivative,...
        'fro')/...
        max(...
        norm(d4{iX},'fro'),...
        eps);


    rmseD2D4(iX) = ...
        sqrt(...
        mean(...
        diffDerivative(:).^2));


    normD2 = ...
        sqrt(...
        sum(...
        d2{iX}.^2,...
        2));


    normD4 = ...
        sqrt(...
        sum(...
        d4{iX}.^2,...
        2));


    fprintf(...
        '\nVariable: %s\n',...
        variableNames{iX})

    fprintf(...
        'Relative D2 vs D4 error = %.12e\n',...
        errorD2D4(iX))

    fprintf(...
        'RMSE D2 vs D4           = %.12e\n',...
        rmseD2D4(iX))

    fprintf(...
        'Mean norm D2            = %.12e\n',...
        mean(normD2))

    fprintf(...
        'Mean norm D4            = %.12e\n',...
        mean(normD4))

end


%% ------------------------------------------------------------
%  D2 VS D4 BY CONSTITUTIVE COMPONENT
% -------------------------------------------------------------

componentNames = {...
    'C1111',...
    'C2222',...
    'C1122',...
    'C1112',...
    'C2212',...
    'C1212'};


componentErrorD2D4 = ...
    zeros(...
    3,...
    nOutputs);


fprintf('\n')
fprintf('============================================\n')
fprintf('       D2 VS D4 BY COMPONENT\n')
fprintf('============================================\n')


for iX = 1:3

    fprintf(...
        '\nDerivative with respect to %s\n',...
        variableNames{iX})


    for iC = 1:nOutputs

        reference = ...
            d4{iX}(:,iC);

        approximation = ...
            d2{iX}(:,iC);


        componentErrorD2D4(iX,iC) = ...
            norm(...
            approximation-reference)/...
            max(...
            norm(reference),...
            eps);


        fprintf(...
            '%s = %.12e\n',...
            componentNames{iC},...
            componentErrorD2D4(iX,iC))

    end

end


%% ------------------------------------------------------------
%  LOAD TRAINED NN
% -------------------------------------------------------------

model = ...
    load(...
    'LatticeNN_FirstModel.mat',...
    'problemNN');

problemNN = ...
    model.problemNN;


fprintf('\nNN model loaded\n')


%% ------------------------------------------------------------
%  ANALYTICAL NN DERIVATIVES
% -------------------------------------------------------------

[~,JNN] = ...
    problemNN.computeOutputValuesAndGradient(...
    XCenter);


dNNrho = ...
    reshape(...
    JNN(1,:,:),...
    nOutputs,...
    nSamples)';


dNNa = ...
    reshape(...
    JNN(2,:,:),...
    nOutputs,...
    nSamples)';


dNNb = ...
    reshape(...
    JNN(3,:,:),...
    nOutputs,...
    nSamples)';


dNN = {...
    dNNrho,...
    dNNa,...
    dNNb};


%% ------------------------------------------------------------
%  SMALL-STEP NN FINITE DIFFERENCE
%
%  This is NOT FEM finite difference.
%
%  We perturb the smooth NN by a very small physical step.
% -------------------------------------------------------------

physicalRange = [...
    rho(end)-rho(1),...
    a(end)-a(1),...
    b(end)-b(1)];


relativeSmallStep = ...
    1e-5;


smallStep = ...
    relativeSmallStep*...
    physicalRange;


fprintf('\nSmall NN finite-difference steps\n')

fprintf(...
    'h_rho = %.12e\n',...
    smallStep(1))

fprintf(...
    'h_a   = %.12e\n',...
    smallStep(2))

fprintf(...
    'h_b   = %.12e\n',...
    smallStep(3))


dNNSmallFD = ...
    cell(3,1);


for iX = 1:3

    XP = ...
        XCenter;

    XM = ...
        XCenter;


    XP(:,iX) = ...
        XP(:,iX) + ...
        smallStep(iX);

    XM(:,iX) = ...
        XM(:,iX) - ...
        smallStep(iX);


    YP = ...
        problemNN.computeOutputValues(...
        XP);

    YM = ...
        problemNN.computeOutputValues(...
        XM);


    dNNSmallFD{iX} = ...
        (YP-YM)/...
        (2*smallStep(iX));

end


%% ------------------------------------------------------------
%  NN ANALYTICAL VS NN SMALL FD
% -------------------------------------------------------------

errorNNInternal = ...
    zeros(3,1);


fprintf('\n')
fprintf('============================================\n')
fprintf('       NN ANALYTICAL VS SMALL FD\n')
fprintf('============================================\n')


for iX = 1:3

    errorNNInternal(iX) = ...
        norm(...
        dNN{iX} - ...
        dNNSmallFD{iX},...
        'fro')/...
        max(...
        norm(dNNSmallFD{iX},'fro'),...
        eps);


    fprintf(...
        '%s = %.12e\n',...
        variableNames{iX},...
        errorNNInternal(iX))

end


%% ------------------------------------------------------------
%  NN ANALYTICAL VS FEM D2 AND D4
% -------------------------------------------------------------

errorNNvsD2 = ...
    zeros(3,1);

errorNNvsD4 = ...
    zeros(3,1);


fprintf('\n')
fprintf('============================================\n')
fprintf('       NN VS FEM DERIVATIVE REFERENCE\n')
fprintf('============================================\n')


for iX = 1:3

    errorNNvsD2(iX) = ...
        norm(...
        dNN{iX}-d2{iX},...
        'fro')/...
        max(...
        norm(d2{iX},'fro'),...
        eps);


    errorNNvsD4(iX) = ...
        norm(...
        dNN{iX}-d4{iX},...
        'fro')/...
        max(...
        norm(d4{iX},'fro'),...
        eps);


    fprintf(...
        '\nVariable: %s\n',...
        variableNames{iX})

    fprintf(...
        'NN analytical vs FEM D2 = %.12e\n',...
        errorNNvsD2(iX))

    fprintf(...
        'NN analytical vs FEM D4 = %.12e\n',...
        errorNNvsD4(iX))

end


%% ------------------------------------------------------------
%  NN VS FEM D4 BY COMPONENT
% -------------------------------------------------------------

componentErrorNNvsD4 = ...
    zeros(...
    3,...
    nOutputs);


fprintf('\n')
fprintf('============================================\n')
fprintf('       NN VS FEM D4 BY COMPONENT\n')
fprintf('============================================\n')


for iX = 1:3

    fprintf(...
        '\nDerivative with respect to %s\n',...
        variableNames{iX})


    for iC = 1:nOutputs

        reference = ...
            d4{iX}(:,iC);

        prediction = ...
            dNN{iX}(:,iC);


        componentErrorNNvsD4(iX,iC) = ...
            norm(...
            prediction-reference)/...
            max(...
            norm(reference),...
            eps);


        fprintf(...
            '%s = %.12e\n',...
            componentNames{iC},...
            componentErrorNNvsD4(iX,iC))

    end

end


%% ------------------------------------------------------------
%  FINITE CHECK
% -------------------------------------------------------------

valuesToCheck = {...
    d2Rho,...
    d2A,...
    d2B,...
    d4Rho,...
    d4A,...
    d4B,...
    dNNrho,...
    dNNa,...
    dNNb,...
    dNNSmallFD{1},...
    dNNSmallFD{2},...
    dNNSmallFD{3}};


for i = 1:length(valuesToCheck)

    if any(...
            ~isfinite(...
            valuesToCheck{i}(:)))

        error(...
            'NaN or Inf detected in derivative check.')

    end

end


fprintf('\nAll derivative values are finite.\n')


