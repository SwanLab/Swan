clc
clear
close all

format long e

rng(1)


fprintf('\n')
fprintf('============================================\n')
fprintf('   LATTICE NN - D4 + SENSITIVITY + ReLoBRaLo\n')
fprintf('============================================\n')


%% ============================================================
%  GENERAL SETTINGS
% =============================================================

mainDataFile = ...
    'LatticeNNData.csv';

sensitivityDataFile = ...
    'LatticeNNSensitivityD4.csv';

sensitivityMatFile = ...
    'LatticeNNSensitivityD4.mat';

modelFile = ...
    'LatticeNN_D4_ReLoBRaLo_100.mat';


componentNames = {...
    'C1111',...
    'C2222',...
    'C1122',...
    'C1112',...
    'C2212',...
    'C1212'};


%% ============================================================
%  1. MAIN VALUE DATA
%
%  Columns:
%
%     1 -> rho
%     2 -> a
%     3 -> b
%
%     4:9 -> independent Chomog components
% =============================================================

sData.fileName = ...
    mainDataFile;

sData.polynomialOrder = ...
    3;

sData.testRatio = ...
    30;

sData.xFeatures = ...
    1:3;

sData.yFeatures = ...
    4:9;


data = ...
    Data(sData);


fprintf('\n')
fprintf('============================================\n')
fprintf('               MAIN DATA\n')
fprintf('============================================\n')

fprintf(...
    'Training samples = %d\n',...
    size(data.Xtrain,1))

fprintf(...
    'Test samples     = %d\n',...
    size(data.Xtest,1))

fprintf(...
    'Input features   = %d\n',...
    data.nFeatures)

fprintf(...
    'Outputs          = %d\n',...
    data.nLabels)


%% ============================================================
%  2. NETWORK
% =============================================================

s = ...
    struct();


s.data = ...
    data;


s.networkParams.hiddenLayers = ...
    [100 200 300 200 100 50];

s.networkParams.HUtype = ...
    'SoftPlus';

s.networkParams.OUtype = ...
    'linear';


%% ============================================================
%  3. VALUE LOSS + REGULARIZATION
%
%     JC + lambda JR
% =============================================================

s.costParams.costType = ...
    'L2';

s.costParams.lambda = ...
    1e-9;


%% ============================================================
%  4. SENSITIVITY DATA
%
%  File columns:
%
%     1:3       rho, a, b
%
%     4:9       dC/drho
%     10:15     dC/da
%     16:21     dC/db
% =============================================================

s.sensitivityParams.sensitivityFileName = ...
    sensitivityDataFile;


%% ------------------------------------------------------------
%  Sensitivity with respect to rho
% -------------------------------------------------------------

s.sensitivityParams.variables(1).name = ...
    'rho';

s.sensitivityParams.variables(1).featureIndex = ...
    1;

s.sensitivityParams.variables(1).targetColumns = ...
    4:9;

s.sensitivityParams.variables(1).h = ...
    1e-5;

s.sensitivityParams.variables(1).weight = ...
    1;


%% ------------------------------------------------------------
%  Sensitivity with respect to a
% -------------------------------------------------------------

s.sensitivityParams.variables(2).name = ...
    'a';

s.sensitivityParams.variables(2).featureIndex = ...
    2;

s.sensitivityParams.variables(2).targetColumns = ...
    10:15;

s.sensitivityParams.variables(2).h = ...
    9.8e-6;

s.sensitivityParams.variables(2).weight = ...
    1;


%% ------------------------------------------------------------
%  Sensitivity with respect to b
% -------------------------------------------------------------

s.sensitivityParams.variables(3).name = ...
    'b';

s.sensitivityParams.variables(3).featureIndex = ...
    3;

s.sensitivityParams.variables(3).targetColumns = ...
    16:21;

s.sensitivityParams.variables(3).h = ...
    2.7e-5;

s.sensitivityParams.variables(3).weight = ...
    1;


%% ============================================================
%  5. ReLoBRaLo
%
%  Shape functions are:
%
%     1 -> JC
%     2 -> Jrho
%     3 -> Ja
%     4 -> Jb
%     5 -> JR
%
%  Balance only:
%
%     JC, Jrho, Ja, Jb
%
%  Regularization is NOT dynamically balanced.
% =============================================================

s.balancingParams.enabled = ...
    true;

s.balancingParams.type = ...
    'ReLoBRaLo';

s.balancingParams.alpha = ...
    0.999;

s.balancingParams.temperature = ...
    0.1;

s.balancingParams.rhoExpected = ...
    0.999;

s.balancingParams.epsilon = ...
    1e-12;


s.balancingParams.balanceMask = ...
    [...
    true;...
    true;...
    true;...
    true;...
    false];


%% ============================================================
%  6. OPTIMIZER
%
%  IMPORTANT:
%
%  This first run is a diagnostic run.
%
%  We use only 100 epochs before committing to a long training.
% =============================================================

s.optimizerParams.learningRate = ...
    5e-3;

s.optimizerParams.maxEpochs = ...
    10000;

s.optimizerParams.earlyStop = ...
    1000;


%% ============================================================
%  7. CREATE PROBLEM
% =============================================================

fprintf('\n')
fprintf('============================================\n')
fprintf('          CREATING NN PROBLEM\n')
fprintf('============================================\n')


problemNN = ...
    OptimizationProblemNN(s);


fprintf('\nProblem created successfully.\n')


%% ============================================================
%  8. INITIAL DIAGNOSTICS
%
%  Full-data diagnostics.
% =============================================================

fprintf('\n')
fprintf('============================================\n')
fprintf('          INITIAL DIAGNOSTICS\n')
fprintf('============================================\n')


problemNN.printLossDiagnostics();

problemNN.printSensitivityDiagnostics();


initialWeights = ...
    problemNN.getEffectiveWeights();


fprintf('\nInitial effective weights\n')

disp(...
    initialWeights')


%% ============================================================
%  9. TRAIN
% =============================================================

fprintf('\n')
fprintf('============================================\n')
fprintf('               TRAINING\n')
fprintf('============================================\n')


tic

problemNN.solve();

trainingTime = ...
    toc;


fprintf('\n')
fprintf(...
    'Total tutorial training time = %.6f s\n',...
    trainingTime)


%% ============================================================
%  10. FINAL LOSS DIAGNOSTICS
% =============================================================

fprintf('\n')
fprintf('============================================\n')
fprintf('           FINAL LOSS DIAGNOSTICS\n')
fprintf('============================================\n')


problemNN.printLossDiagnostics();

problemNN.printSensitivityDiagnostics();


finalWeights = ...
    problemNN.getEffectiveWeights();


fprintf('\nFinal effective weights\n')

disp(...
    finalWeights')


%% ============================================================
%  11. VALUE ERRORS
% =============================================================

XtrainPhysical = ...
    data.XtrainPhysical;

YtrainPhysical = ...
    data.YtrainPhysical;

XtestPhysical = ...
    data.XtestPhysical;

YtestPhysical = ...
    data.YtestPhysical;


YtrainPred = ...
    problemNN.computeOutputValues(...
    XtrainPhysical);

YtestPred = ...
    problemNN.computeOutputValues(...
    XtestPhysical);


trainRelativeError = ...
    norm(...
    YtrainPred-YtrainPhysical,...
    'fro')/...
    max(...
    norm(YtrainPhysical,'fro'),...
    eps);


testRelativeError = ...
    norm(...
    YtestPred-YtestPhysical,...
    'fro')/...
    max(...
    norm(YtestPhysical,'fro'),...
    eps);


fprintf('\n')
fprintf('============================================\n')
fprintf('             GLOBAL VALUE ERRORS\n')
fprintf('============================================\n')


fprintf(...
    'Training relative error = %.12e\n',...
    trainRelativeError)

fprintf(...
    'Test relative error     = %.12e\n',...
    testRelativeError)


%% ============================================================
%  12. TEST ERROR BY COMPONENT
% =============================================================

componentRelativeError = ...
    zeros(6,1);

componentMAE = ...
    zeros(6,1);

componentMaxError = ...
    zeros(6,1);


fprintf('\n')
fprintf('============================================\n')
fprintf('        ERROR BY TENSOR COMPONENT\n')
fprintf('============================================\n')


for iC = 1:6

    target = ...
        YtestPhysical(:,iC);

    prediction = ...
        YtestPred(:,iC);


    componentRelativeError(iC) = ...
        norm(...
        prediction-target)/...
        max(...
        norm(target),...
        eps);


    componentMAE(iC) = ...
        mean(...
        abs(...
        prediction-target));


    componentMaxError(iC) = ...
        max(...
        abs(...
        prediction-target));


    fprintf(...
        '%s\n',...
        componentNames{iC})

    fprintf(...
        '  Relative error = %.12e\n',...
        componentRelativeError(iC))

    fprintf(...
        '  MAE            = %.12e\n',...
        componentMAE(iC))

    fprintf(...
        '  Max abs error  = %.12e\n',...
        componentMaxError(iC))

end


%% ============================================================
%  13. LOAD D4 REFERENCE
% =============================================================

sens = ...
    load(...
    sensitivityMatFile,...
    'XPhysical',...
    'dCdrhoD4',...
    'dCdaD4',...
    'dCdbD4');


XDerivative = ...
    sens.XPhysical;

dCdrhoD4 = ...
    sens.dCdrhoD4;

dCdaD4 = ...
    sens.dCdaD4;

dCdbD4 = ...
    sens.dCdbD4;


nDerivativeSamples = ...
    size(...
    XDerivative,...
    1);


fprintf('\n')
fprintf('============================================\n')
fprintf('          D4 DERIVATIVE VALIDATION\n')
fprintf('============================================\n')

fprintf(...
    'Derivative samples = %d\n',...
    nDerivativeSamples)


%% ============================================================
%  14. NN ANALYTICAL PHYSICAL JACOBIAN
% =============================================================

[~,JNN] = ...
    problemNN.computeOutputValuesAndGradient(...
    XDerivative);


nOutputs = ...
    6;


dNNrho = ...
    reshape(...
    JNN(1,:,:),...
    nOutputs,...
    nDerivativeSamples)';


dNNa = ...
    reshape(...
    JNN(2,:,:),...
    nOutputs,...
    nDerivativeSamples)';


dNNb = ...
    reshape(...
    JNN(3,:,:),...
    nOutputs,...
    nDerivativeSamples)';


if any(~isfinite(JNN(:)))

    error(...
        'Non-finite NN Jacobian detected.')

end


%% ============================================================
%  15. GLOBAL DERIVATIVE ERRORS
% =============================================================

errorRho = ...
    norm(...
    dNNrho-dCdrhoD4,...
    'fro')/...
    max(...
    norm(dCdrhoD4,'fro'),...
    eps);


errorA = ...
    norm(...
    dNNa-dCdaD4,...
    'fro')/...
    max(...
    norm(dCdaD4,'fro'),...
    eps);


errorB = ...
    norm(...
    dNNb-dCdbD4,...
    'fro')/...
    max(...
    norm(dCdbD4,'fro'),...
    eps);


fprintf('\n')

fprintf(...
    'dC/drho: NN vs FEM D4 = %.12e\n',...
    errorRho)

fprintf(...
    'dC/da:   NN vs FEM D4 = %.12e\n',...
    errorA)

fprintf(...
    'dC/db:   NN vs FEM D4 = %.12e\n',...
    errorB)


%% ============================================================
%  16. DERIVATIVE ERRORS BY COMPONENT
% =============================================================

componentErrorRho = ...
    zeros(6,1);

componentErrorA = ...
    zeros(6,1);

componentErrorB = ...
    zeros(6,1);


fprintf('\n')
fprintf('============================================\n')
fprintf('       D4 ERROR BY TENSOR COMPONENT\n')
fprintf('============================================\n')


fprintf('\nDerivative with respect to rho\n')

for iC = 1:6

    componentErrorRho(iC) = ...
        norm(...
        dNNrho(:,iC) - ...
        dCdrhoD4(:,iC))/...
        max(...
        norm(...
        dCdrhoD4(:,iC)),...
        eps);


    fprintf(...
        '%s = %.12e\n',...
        componentNames{iC},...
        componentErrorRho(iC))

end


fprintf('\nDerivative with respect to a\n')

for iC = 1:6

    componentErrorA(iC) = ...
        norm(...
        dNNa(:,iC) - ...
        dCdaD4(:,iC))/...
        max(...
        norm(...
        dCdaD4(:,iC)),...
        eps);


    fprintf(...
        '%s = %.12e\n',...
        componentNames{iC},...
        componentErrorA(iC))

end


fprintf('\nDerivative with respect to b\n')

for iC = 1:6

    componentErrorB(iC) = ...
        norm(...
        dNNb(:,iC) - ...
        dCdbD4(:,iC))/...
        max(...
        norm(...
        dCdbD4(:,iC)),...
        eps);


    fprintf(...
        '%s = %.12e\n',...
        componentNames{iC},...
        componentErrorB(iC))

end


%% ============================================================
%  17. DERIVATIVE MAGNITUDES
% =============================================================

normFEMrho = ...
    sqrt(...
    sum(...
    dCdrhoD4.^2,...
    2));

normFEMa = ...
    sqrt(...
    sum(...
    dCdaD4.^2,...
    2));

normFEMb = ...
    sqrt(...
    sum(...
    dCdbD4.^2,...
    2));


normNNrho = ...
    sqrt(...
    sum(...
    dNNrho.^2,...
    2));

normNNa = ...
    sqrt(...
    sum(...
    dNNa.^2,...
    2));

normNNb = ...
    sqrt(...
    sum(...
    dNNb.^2,...
    2));


fprintf('\n')
fprintf('============================================\n')
fprintf('          DERIVATIVE MAGNITUDES\n')
fprintf('============================================\n')


fprintf('\ndC/drho\n')
fprintf(...
    'FEM D4 mean norm = %.12e\n',...
    mean(normFEMrho))
fprintf(...
    'NN mean norm     = %.12e\n',...
    mean(normNNrho))


fprintf('\ndC/da\n')
fprintf(...
    'FEM D4 mean norm = %.12e\n',...
    mean(normFEMa))
fprintf(...
    'NN mean norm     = %.12e\n',...
    mean(normNNa))


fprintf('\ndC/db\n')
fprintf(...
    'FEM D4 mean norm = %.12e\n',...
    mean(normFEMb))
fprintf(...
    'NN mean norm     = %.12e\n',...
    mean(normNNb))


%% ============================================================
%  18. ReLoBRaLo HISTORY
% =============================================================

history = ...
    problemNN.getBalancingHistory();


fprintf('\n')
fprintf('============================================\n')
fprintf('            ReLoBRaLo HISTORY\n')
fprintf('============================================\n')


fprintf(...
    'Stored balancing steps = %d\n',...
    size(history.weights,2))


if ~isempty(history.weights)

    fprintf('\nLast ReLoBRaLo weights\n')

    fprintf(...
        'w_C   = %.12e\n',...
        history.weights(1,end))

    fprintf(...
        'w_rho = %.12e\n',...
        history.weights(2,end))

    fprintf(...
        'w_a   = %.12e\n',...
        history.weights(3,end))

    fprintf(...
        'w_b   = %.12e\n',...
        history.weights(4,end))


    fprintf(...
        '\nSum final balanced weights = %.12e\n',...
        sum(...
        history.weights(:,end)))

end


%% ============================================================
%  19. PLOT ReLoBRaLo WEIGHTS
