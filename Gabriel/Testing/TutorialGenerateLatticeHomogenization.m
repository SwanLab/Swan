clc
clear
close all

fprintf('\n')
fprintf('============================================\n')
fprintf('      LATTICE HOMOGENIZATION DATABASE\n')
fprintf('============================================\n')

tic

lattice = ...
    TutorialLatticeNN();

totalTime = ...
    toc;


%% Extract FEM data

rho = ...
    lattice.rho(:);

a = ...
    lattice.a(:);

b = ...
    lattice.b(:);

Chomog = ...
    lattice.Chomog;


%% Dimensions

nRho = ...
    length(rho);

nA = ...
    length(a);

nB = ...
    length(b);

expectedSize = ...
    [...
    2,...
    2,...
    2,...
    2,...
    nRho,...
    nA,...
    nB];

actualSize = ...
    size(Chomog);


%% Checks

if ~isequal(...
        actualSize,...
        expectedSize)

    error(...
        ['Unexpected Chomog size. ',...
         'Expected [%s], obtained [%s].'],...
        num2str(expectedSize),...
        num2str(actualSize))

end

if any(...
        ~isfinite(Chomog(:)))

    error(...
        'Chomog contains NaN or Inf values.')

end


%% Summary

fprintf('\nParameter values\n')

fprintf('\nrho\n')
disp(rho')

fprintf('a\n')
disp(a')

fprintf('b\n')
disp(b')


fprintf('\nNumber of parameter values\n')

fprintf(...
    'nRho = %d\n',...
    nRho)

fprintf(...
    'nA   = %d\n',...
    nA)

fprintf(...
    'nB   = %d\n',...
    nB)


fprintf('\nNumber of FEM homogenizations\n')

fprintf(...
    '%d x %d x %d = %d\n',...
    nRho,...
    nA,...
    nB,...
    nRho*nA*nB)


fprintf('\nChomog size\n')

disp(...
    actualSize)


fprintf('\nParameter ranges\n')

fprintf(...
    'rho: [%g, %g]\n',...
    min(rho),...
    max(rho))

fprintf(...
    'a:   [%g, %g]\n',...
    min(a),...
    max(a))

fprintf(...
    'b:   [%g, %g]\n',...
    min(b),...
    max(b))


%% Tensor symmetry checks

Cminor1 = ...
    permute(...
    Chomog,...
    [2 1 3 4 5 6 7]);

Cminor2 = ...
    permute(...
    Chomog,...
    [1 2 4 3 5 6 7]);

Cmajor = ...
    permute(...
    Chomog,...
    [3 4 1 2 5 6 7]);

errorMinor1 = ...
    max(...
    abs(...
    Chomog(:)-...
    Cminor1(:)));

errorMinor2 = ...
    max(...
    abs(...
    Chomog(:)-...
    Cminor2(:)));

errorMajor = ...
    max(...
    abs(...
    Chomog(:)-...
    Cmajor(:)));


fprintf('\nTensor symmetry errors\n')

fprintf(...
    'minor ij = %.12e\n',...
    errorMinor1)

fprintf(...
    'minor kl = %.12e\n',...
    errorMinor2)

fprintf(...
    'major    = %.12e\n',...
    errorMajor)


%% Save FEM database

fileName = ...
    'LatticeHomogenization.mat';

save(...
    fileName,...
    'rho',...
    'a',...
    'b',...
    'Chomog',...
    '-v7.3')


fprintf('\nFile created\n')

fprintf(...
    '%s\n',...
    fileName)

fprintf(...
    '\nTotal computation time = %.2f s\n',...
    totalTime)

fprintf('\n')
fprintf('============================================\n')
fprintf('     HOMOGENIZATION DATABASE COMPLETED\n')
fprintf('============================================\n')