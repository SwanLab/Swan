clc
clear
close all

fprintf('\n')
fprintf('============================================\n')
fprintf('       PREPARE LATTICE NN FEM DATA\n')
fprintf('============================================\n')


%% Load homogenization database

fileName = ...
    'LatticeHomogenization.mat';

load(...
    fileName,...
    'rho',...
    'a',...
    'b',...
    'Chomog')


%% Parameter vectors

rho = ...
    rho(:);

a = ...
    a(:);

b = ...
    b(:);

nRho = ...
    length(rho);

nA = ...
    length(a);

nB = ...
    length(b);

nSamples = ...
    nRho*nA*nB;


%% Check Chomog dimensions

expectedSize = ...
    [...
    2,...
    2,...
    2,...
    2,...
    nRho,...
    nA,...
    nB];

actualSize = ...
    size(Chomog);

if ~isequal(...
        actualSize,...
        expectedSize)

    error(...
        ['Unexpected Chomog size. ',...
         'Expected [%s], obtained [%s].'],...
        num2str(expectedSize),...
        num2str(actualSize))

end

if any(...
        ~isfinite(Chomog(:)))

    error(...
        'Chomog contains NaN or Inf values.')

end


%% Create structured parameter grid

[R,A,B] = ...
    ndgrid(...
    rho,...
    a,...
    b);


%% Extract independent tensor components

C1111 = ...
    reshape(...
    Chomog(1,1,1,1,:,:,:),...
    nRho,...
    nA,...
    nB);

C2222 = ...
    reshape(...
    Chomog(2,2,2,2,:,:,:),...
    nRho,...
    nA,...
    nB);

C1122 = ...
    reshape(...
    Chomog(1,1,2,2,:,:,:),...
    nRho,...
    nA,...
    nB);

C1112 = ...
    reshape(...
    Chomog(1,1,1,2,:,:,:),...
    nRho,...
    nA,...
    nB);

C2212 = ...
    reshape(...
    Chomog(2,2,1,2,:,:,:),...
    nRho,...
    nA,...
    nB);

C1212 = ...
    reshape(...
    Chomog(1,2,1,2,:,:,:),...
    nRho,...
    nA,...
    nB);


%% Assemble dataset

dataset = [...
    R(:),...
    A(:),...
    B(:),...
    C1111(:),...
    C2222(:),...
    C1122(:),...
    C1112(:),...
    C2212(:),...
    C1212(:)];


%% Separate input and output matrices

XPhysical = ...
    dataset(:,1:3);

YPhysical = ...
    dataset(:,4:9);


%% Basic checks

if size(dataset,1) ~= nSamples

    error(...
        'Unexpected number of dataset samples.')

end

if size(dataset,2) ~= 9

    error(...
        'Dataset must contain 9 columns.')

end

if any(...
        ~isfinite(dataset(:)))

    error(...
        'Dataset contains NaN or Inf values.')

end


%% Summary

fprintf('\nParameter dimensions\n')

fprintf(...
    'nRho = %d\n',...
    nRho)

fprintf(...
    'nA   = %d\n',...
    nA)

fprintf(...
    'nB   = %d\n',...
    nB)

fprintf(...
    '\nNumber of samples = %d\n',...
    nSamples)

fprintf(...
    'Number of inputs  = %d\n',...
    size(XPhysical,2))

fprintf(...
    'Number of outputs = %d\n',...
    size(YPhysical,2))


fprintf('\nDataset size\n')

disp(...
    size(dataset))


%% Physical input statistics

fprintf('\n')
fprintf('Physical input statistics\n')
fprintf('\n')

fprintf(...
    '              min           max           mean          std\n')

disp([...
    min(XPhysical,[],1)',...
    max(XPhysical,[],1)',...
    mean(XPhysical,1)',...
    std(XPhysical,0,1)'])


%% Physical output statistics

fprintf('\n')
fprintf('Physical output statistics\n')
fprintf('\n')

fprintf(...
    '              min           max           mean          std\n')

disp([...
    min(YPhysical,[],1)',...
    max(YPhysical,[],1)',...
    mean(YPhysical,1)',...
    std(YPhysical,0,1)'])


fprintf('\nMaximum absolute value per output\n')

disp(...
    max(...
    abs(YPhysical),...
    [],...
    1))


%% Check parameter ranges in dataset

fprintf('\nDataset input ranges\n')

disp([...
    min(XPhysical,[],1);
    max(XPhysical,[],1)])


%% Save dataset

csvFileName = ...
    'LatticeNNData.csv';

matFileName = ...
    'LatticeNNData.mat';

writematrix(...
    dataset,...
    csvFileName)

save(...
    matFileName,...
    'dataset',...
    'XPhysical',...
    'YPhysical',...
    'rho',...
    'a',...
    'b',...
    '-v7.3')


%% Final information

fprintf('\nFiles created\n')

fprintf(...
    '%s\n',...
    csvFileName)

fprintf(...
    '%s\n',...
    matFileName)


fprintf('\nDataset column layout\n')

fprintf(...
    '1 -> rho\n')

fprintf(...
    '2 -> a\n')

fprintf(...
    '3 -> b\n')

fprintf(...
    '4 -> C1111\n')

fprintf(...
    '5 -> C2222\n')

fprintf(...
    '6 -> C1122\n')

fprintf(...
    '7 -> C1112\n')

fprintf(...
    '8 -> C2212\n')

fprintf(...
    '9 -> C1212\n')


fprintf('\n')
fprintf('============================================\n')
fprintf('       LATTICE NN DATA PREPARED\n')
fprintf('============================================\n')