    'XCenter',...
    'dCdrhoFEM',...
    'dCdaFEM',...
    'dCdbFEM',...
    'dCdrhoNN',...
    'dCdaNN',...
    'dCdbNN',...
    'dCdrhoNNFD',...
    'dCdaNNFD',...
    'dCdbNNFD',...
    'errorAnalytical',...
    'errorNNFD',...
    'errorNNInternal',...
    'componentError',...
    'functionError',...
    '-v7.3');


fprintf('\n')
fprintf('Saved: LatticeNNDerivativeValidation.mat\n')

