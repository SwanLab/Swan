fprintf('\n')
fprintf('============================================\n')
fprintf('      LATTICE NN DERIVATIVE VALIDATION\n')
fprintf('============================================\n')


%% ------------------------------------------------------------
%  LOAD FEM DATABASE
% -------------------------------------------------------------

fem = ...
    load(...
    'LatticeHomogenization.mat',...
    'rho',...
    'a',...
    'b',...
    'Chomog');

rho = ...
    fem.rho(:);

a = ...
    fem.a(:);

b = ...
    fem.b(:);

Chomog = ...
    fem.Chomog;


nRho = ...
    length(rho);

nA = ...
    length(a);

nB = ...
    length(b);


fprintf('\nFEM database loaded\n')

fprintf(...
    'rho points = %d\n',...
    nRho)

fprintf(...
    'a points   = %d\n',...
    nA)

fprintf(...
    'b points   = %d\n',...
    nB)


%% ------------------------------------------------------------
%  LOAD TRAINED NN
% -------------------------------------------------------------

model = ...
    load(...
    'LatticeNN_FirstModel.mat',...
    'problemNN');

problemNN = ...
    model.problemNN;


fprintf('\nNN model loaded\n')


%% ------------------------------------------------------------
%  BUILD CONSTITUTIVE ARRAY
%
%  C(:,:,:,1) = C1111
%  C(:,:,:,2) = C2222
%  C(:,:,:,3) = C1122
%  C(:,:,:,4) = C1112
%  C(:,:,:,5) = C2212
%  C(:,:,:,6) = C1212
% -------------------------------------------------------------

nOutputs = ...
    6;

C = ...
    zeros(...
    nRho,...
    nA,...
    nB,...
    nOutputs);


C(:,:,:,1) = ...
    reshape(...
    Chomog(1,1,1,1,:,:,:),...
    nRho,...
    nA,...
    nB);

C(:,:,:,2) = ...
    reshape(...
    Chomog(2,2,2,2,:,:,:),...
    nRho,...
    nA,...
    nB);

C(:,:,:,3) = ...
    reshape(...
    Chomog(1,1,2,2,:,:,:),...
    nRho,...
    nA,...
    nB);

C(:,:,:,4) = ...
    reshape(...
    Chomog(1,1,1,2,:,:,:),...
    nRho,...
    nA,...
    nB);

C(:,:,:,5) = ...
    reshape(...
    Chomog(2,2,1,2,:,:,:),...
    nRho,...
    nA,...
    nB);

C(:,:,:,6) = ...
    reshape(...
    Chomog(1,2,1,2,:,:,:),...
    nRho,...
    nA,...
    nB);


%% ------------------------------------------------------------
%  INTERIOR GRID
%
%  Central differences require:
%
%       2 <= iRho <= nRho-1
%       2 <= iA   <= nA-1
%       2 <= iB   <= nB-1
% -------------------------------------------------------------

rhoI = ...
    rho(2:end-1);

aI = ...
    a(2:end-1);

bI = ...
    b(2:end-1);


[R,A,B] = ...
    ndgrid(...
    rhoI,...
    aI,...
    bI);


XCenter = ...
    [...
    R(:),...
    A(:),...
    B(:)];


nSamples = ...
    size(XCenter,1);


fprintf('\nInterior validation points = %d\n',...
    nSamples)


%% ------------------------------------------------------------
%  FEM CENTRAL DIFFERENCE: dC / drho
% -------------------------------------------------------------

denRho = ...
    reshape(...
    rho(3:end)-rho(1:end-2),...
    [],1,1,1);


dCdrhoFEM4D = ...
    (...
    C(3:end,2:end-1,2:end-1,:) - ...
    C(1:end-2,2:end-1,2:end-1,:)...
    )./denRho;


dCdrhoFEM = ...
    reshape(...
    dCdrhoFEM4D,...
    nSamples,...
    nOutputs);


%% ------------------------------------------------------------
%  FEM CENTRAL DIFFERENCE: dC / da
% -------------------------------------------------------------

denA = ...
    reshape(...
    a(3:end)-a(1:end-2),...
    1,[],1,1);


dCdaFEM4D = ...
    (...
    C(2:end-1,3:end,2:end-1,:) - ...
    C(2:end-1,1:end-2,2:end-1,:)...
    )./denA;


dCdaFEM = ...
    reshape(...
    dCdaFEM4D,...
    nSamples,...
    nOutputs);


%% ------------------------------------------------------------
%  FEM CENTRAL DIFFERENCE: dC / db
% -------------------------------------------------------------

denB = ...
    reshape(...
    b(3:end)-b(1:end-2),...
    1,1,[],1);


dCdbFEM4D = ...
    (...
    C(2:end-1,2:end-1,3:end,:) - ...
    C(2:end-1,2:end-1,1:end-2,:)...
    )./denB;


dCdbFEM = ...
    reshape(...
    dCdbFEM4D,...
    nSamples,...
    nOutputs);


%% ------------------------------------------------------------
%  ANALYTICAL NN JACOBIAN
% -------------------------------------------------------------

[CcenterNN,JNN] = ...
    problemNN.computeOutputValuesAndGradient(...
    XCenter);


dCdrhoNN = ...
    reshape(...
    JNN(1,:,:),...
    nOutputs,...
    nSamples)';


dCdaNN = ...
    reshape(...
    JNN(2,:,:),...
    nOutputs,...
    nSamples)';


dCdbNN = ...
    reshape(...
    JNN(3,:,:),...
    nOutputs,...
    nSamples)';


%% ------------------------------------------------------------
%  CREATE NEIGHBORING PHYSICAL POINTS
% -------------------------------------------------------------

% rho +

[Rp,Ap,Bp] = ...
    ndgrid(...
    rho(3:end),...
    aI,...
    bI);

XrhoPlus = ...
    [Rp(:),Ap(:),Bp(:)];


% rho -

[Rm,Am,Bm] = ...
    ndgrid(...
    rho(1:end-2),...
    aI,...
    bI);

XrhoMinus = ...
    [Rm(:),Am(:),Bm(:)];


% a +

[Rp,Ap,Bp] = ...
    ndgrid(...
    rhoI,...
    a(3:end),...
    bI);

XaPlus = ...
    [Rp(:),Ap(:),Bp(:)];


% a -

[Rm,Am,Bm] = ...
    ndgrid(...
    rhoI,...
    a(1:end-2),...
    bI);

XaMinus = ...
    [Rm(:),Am(:),Bm(:)];


% b +

[Rp,Ap,Bp] = ...
    ndgrid(...
    rhoI,...
    aI,...
    b(3:end));

XbPlus = ...
    [Rp(:),Ap(:),Bp(:)];


% b -

[Rm,Am,Bm] = ...
    ndgrid(...
    rhoI,...
    aI,...
    b(1:end-2));

XbMinus = ...
    [Rm(:),Am(:),Bm(:)];


%% ------------------------------------------------------------
%  NN CENTRAL FINITE DIFFERENCES
%
%  Same stencil and same physical spacing as FEM database.
% -------------------------------------------------------------

CrhoPlus = ...
    problemNN.computeOutputValues(...
    XrhoPlus);

CrhoMinus = ...
    problemNN.computeOutputValues(...
    XrhoMinus);


CaPlus = ...
    problemNN.computeOutputValues(...
    XaPlus);

CaMinus = ...
    problemNN.computeOutputValues(...
    XaMinus);


CbPlus = ...
    problemNN.computeOutputValues(...
    XbPlus);

CbMinus = ...
    problemNN.computeOutputValues(...
    XbMinus);


%% ------------------------------------------------------------
%  DENOMINATORS IN VECTOR FORM
% -------------------------------------------------------------

[DRho,~,~] = ...
    ndgrid(...
    rho(3:end)-rho(1:end-2),...
    aI,...
    bI);

denRhoVec = ...
    DRho(:);


[~,DA,~] = ...
    ndgrid(...
    rhoI,...
    a(3:end)-a(1:end-2),...
    bI);

denAVec = ...
    DA(:);


[~,~,DB] = ...
    ndgrid(...
    rhoI,...
    aI,...
    b(3:end)-b(1:end-2));

denBVec = ...
    DB(:);


%% ------------------------------------------------------------
%  NN FINITE DIFFERENCE DERIVATIVES
% -------------------------------------------------------------

dCdrhoNNFD = ...
    (CrhoPlus-CrhoMinus)./...
    denRhoVec;


dCdaNNFD = ...
    (CaPlus-CaMinus)./...
    denAVec;


dCdbNNFD = ...
    (CbPlus-CbMinus)./...
    denBVec;


%% ------------------------------------------------------------
%  GLOBAL DERIVATIVE ERRORS
% -------------------------------------------------------------

variables = {...
    'rho',...
    'a',...
    'b'};


dFEM = {...
    dCdrhoFEM,...
    dCdaFEM,...
    dCdbFEM};


dNN = {...
    dCdrhoNN,...
    dCdaNN,...
    dCdbNN};


dNNFD = {...
    dCdrhoNNFD,...
    dCdaNNFD,...
    dCdbNNFD};


errorAnalytical = ...
    zeros(3,1);

errorNNFD = ...
    zeros(3,1);

errorNNInternal = ...
    zeros(3,1);


fprintf('\n')
fprintf('============================================\n')
fprintf('         GLOBAL DERIVATIVE ERRORS\n')
fprintf('============================================\n')


for iX = 1:3

    reference = ...
        dFEM{iX};

    analytical = ...
        dNN{iX};

    finiteNN = ...
        dNNFD{iX};


    errorAnalytical(iX) = ...
        norm(...
        analytical-reference,...
        'fro')/...
        max(...
        norm(reference,'fro'),...
        eps);


    errorNNFD(iX) = ...
        norm(...
        finiteNN-reference,...
        'fro')/...
        max(...
        norm(reference,'fro'),...
        eps);


    errorNNInternal(iX) = ...
        norm(...
        analytical-finiteNN,...
        'fro')/...
        max(...
        norm(finiteNN,'fro'),...
        eps);


    fprintf(...
        '\nVariable: %s\n',...
        variables{iX})

    fprintf(...
        'NN analytical vs FEM FD = %.12e\n',...
        errorAnalytical(iX))

    fprintf(...
        'NN FD         vs FEM FD = %.12e\n',...
        errorNNFD(iX))

    fprintf(...
        'NN analytical vs NN FD  = %.12e\n',...
        errorNNInternal(iX))

end


%% ------------------------------------------------------------
%  DERIVATIVE ERROR BY CONSTITUTIVE COMPONENT
% -------------------------------------------------------------

componentNames = {...
    'C1111',...
    'C2222',...
    'C1122',...
    'C1112',...
    'C2212',...
    'C1212'};


componentError = ...
    zeros(...
    3,...
    nOutputs);


fprintf('\n')
fprintf('============================================\n')
fprintf('      DERIVATIVE ERROR BY COMPONENT\n')
fprintf('============================================\n')


for iX = 1:3

    fprintf(...
        '\nDerivative with respect to %s\n',...
        variables{iX})


    for iC = 1:nOutputs

        reference = ...
            dFEM{iX}(:,iC);

        prediction = ...
            dNN{iX}(:,iC);


        componentError(iX,iC) = ...
            norm(...
            prediction-reference)/...
            max(...
            norm(reference),...
            eps);


        fprintf(...
            '%s = %.12e\n',...
            componentNames{iC},...
            componentError(iX,iC))

    end

end


%% ------------------------------------------------------------
%  MEAN DERIVATIVE MAGNITUDES
% -------------------------------------------------------------

fprintf('\n')
fprintf('============================================\n')
fprintf('         DERIVATIVE MAGNITUDES\n')
fprintf('============================================\n')


for iX = 1:3

    femNorm = ...
        sqrt(...
        sum(...
        dFEM{iX}.^2,...
        2));

    nnNorm = ...
        sqrt(...
        sum(...
        dNN{iX}.^2,...
        2));


    fprintf(...
        '\n%s\n',...
        variables{iX})

    fprintf(...
        'Mean FEM norm = %.12e\n',...
        mean(femNorm))

    fprintf(...
        'Mean NN norm  = %.12e\n',...
        mean(nnNorm))

end


%% ------------------------------------------------------------
%  DERIVATIVE ERROR BY RHO REGION
% -------------------------------------------------------------

regions = [...
    0.00 0.20;
    0.20 0.40;
    0.40 0.60;
    0.60 0.80;
    0.80 1.00];


fprintf('\n')
fprintf('============================================\n')
fprintf('     DERIVATIVE ERROR BY RHO REGION\n')
fprintf('============================================\n')


rhoCenter = ...
    XCenter(:,1);


for iX = 1:3

    fprintf(...
        '\nDerivative with respect to %s\n',...
        variables{iX})


    for iR = 1:size(regions,1)

        rhoMin = ...
            regions(iR,1);

        rhoMax = ...
            regions(iR,2);


        if iR < size(regions,1)

            indices = ...
                rhoCenter >= rhoMin & ...
                rhoCenter < rhoMax;

        else

            indices = ...
                rhoCenter >= rhoMin & ...
                rhoCenter <= rhoMax;

        end


        reference = ...
            dFEM{iX}(indices,:);

        prediction = ...
            dNN{iX}(indices,:);


        if isempty(reference)

            continue

        end


        errorRegion = ...
            norm(...
            prediction-reference,...
            'fro')/...
            max(...
            norm(reference,'fro'),...
            eps);


        fprintf(...
            'rho = [%.2f, %.2f] -> error = %.12e  N = %d\n',...
            rhoMin,...
            rhoMax,...
            errorRegion,...
            sum(indices))

    end

end


%% ------------------------------------------------------------
%  FUNCTION ERROR ON INTERIOR POINTS
% -------------------------------------------------------------

CcenterFEM = ...
    reshape(...
    C(2:end-1,2:end-1,2:end-1,:),...
    nSamples,...
    nOutputs);


functionError = ...
    norm(...
    CcenterNN-CcenterFEM,...
    'fro')/...
    max(...
    norm(CcenterFEM,'fro'),...
    eps);


fprintf('\n')
fprintf('============================================\n')
fprintf('       INTERIOR FUNCTION ERROR\n')
fprintf('============================================\n')

fprintf(...
    'Relative C error = %.12e\n',...
    functionError)


%% ------------------------------------------------------------
%  FINITE CHECK
% -------------------------------------------------------------

allValues = {...
    dCdrhoFEM,...
    dCdaFEM,...
    dCdbFEM,...
    dCdrhoNN,...
    dCdaNN,...
    dCdbNN,...
    dCdrhoNNFD,...
    dCdaNNFD,...
    dCdbNNFD};


for i = 1:length(allValues)

    if any(...
            ~isfinite(...
            allValues{i}(:)))

        error(...
            'NaN or Inf detected in derivative validation.')

    end

end


fprintf('\nAll derivative validation values are finite.\n')


