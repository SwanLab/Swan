%% ========================================================================
% 10 - CONSTITUTIVE SENSITIVITY COMPETITION
%
% Same diagnostic used in validation:
%
%       Sb   = Delta_b   ||C_,b||
%       Srho = Delta_rho ||C_,rho||
%
% We use the four primary orthotropic components:
%
%       C1111
%       C1122
%       C2222
%       C1212
%
%% ========================================================================

id11 = 1;
id12 = 2;
id22 = 4;
id66 = 6;


normB_H = sqrt( ...
    dB_hom(:,:,id11).^2 + ...
    2*dB_hom(:,:,id12).^2 + ...
    dB_hom(:,:,id22).^2 + ...
    dB_hom(:,:,id66).^2);


normR_H = sqrt( ...
    dRho_hom(:,:,id11).^2 + ...
    2*dRho_hom(:,:,id12).^2 + ...
    dRho_hom(:,:,id22).^2 + ...
    dRho_hom(:,:,id66).^2);


normB_N = sqrt( ...
    dB_nn(:,:,id11).^2 + ...
    2*dB_nn(:,:,id12).^2 + ...
    dB_nn(:,:,id22).^2 + ...
    dB_nn(:,:,id66).^2);


normR_N = sqrt( ...
    dRho_nn(:,:,id11).^2 + ...
    2*dRho_nn(:,:,id12).^2 + ...
    dRho_nn(:,:,id22).^2 + ...
    dRho_nn(:,:,id66).^2);


deltaB = ...
    max(paramB)-min(paramB);

deltaRho = ...
    max(paramRho)-min(paramRho);


Sb_H = ...
    deltaB*normB_H;

Sr_H = ...
    deltaRho*normR_H;


Sb_N = ...
    deltaB*normB_N;

Sr_N = ...
    deltaRho*normR_N;


ratioSensitivityH = ...
    Sb_H ./ max(Sr_H,eps);

ratioSensitivityN = ...
    Sb_N ./ max(Sr_N,eps);


logRatioH = ...
    log10(ratioSensitivityH);

logRatioN = ...
    log10(ratioSensitivityN);


