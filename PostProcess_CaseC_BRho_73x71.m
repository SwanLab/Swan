%% ========================================================================
%  POST-PROCESS - CASE C - NEW b-rho FORMULATION
%
%  Current formulation:
%
%       parameters = (b,rho)
%
%       b   in [1/3,3]
%       rho in [~0,0.998]
%
%       eta(b) =
%       kappa * (b - 1/b)/(bmax - 1/bmax)
%
%  Current dataset:
%
%       nB   = 73
%       nRho = 71
%
%  Network:
%
%       input transforms = identity, identity
%       hidden layers    = [150 200 300 200 150 50]
%       activation       = tanh
%       epochs           = 100000
%
%  Outputs:
%
%       HOM / NN surfaces
%       HOM-vs-NN errors
%       value curves
%       dC/db curves
%       dC/drho curves
%       b = 1 symmetry tests
%       anisotropy ratio
%       sensitivity competition Sb/Srho
%       volume fraction
%
%% ========================================================================

close all
clc


%% ========================================================================
% CONFIGURATION
%% ========================================================================

dataFile = ...
    'Homogenizationtwovariables28NEW.mat';

historyFile = ...
    'NNhistory_CaseC_brho_identity_tanh_100k.mat';

outFolder = ...
    'PostProcess_CaseC_73x71_Output';

if ~exist(outFolder,'dir')
    mkdir(outFolder);
end


%% ========================================================================
% LOAD DATA
%% ========================================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf(' CASE C - b-rho POST-PROCESS\n');
fprintf('============================================================\n');

fprintf('Loading:\n%s\n\n',dataFile);

H = load(dataFile);

assert(isfield(H,'Chomog'), ...
    'Chomog is missing.');

assert(isfield(H,'paramB'), ...
    'paramB is missing.');

assert(isfield(H,'paramRho'), ...
    'paramRho is missing.');

assert(isfield(H,'volFrac'), ...
    'volFrac is missing.');

assert(isfield(H,'Interpolation'), ...
    'Interpolation is missing.');


Chomog        = H.Chomog;
paramB        = H.paramB(:)';
paramRho      = H.paramRho(:);
volFrac       = H.volFrac;
Interpolation = H.Interpolation;


nB   = numel(paramB);
nRho = numel(paramRho);

db   = mean(diff(paramB));
drho = mean(diff(paramRho));


fprintf('Grid = %d rho x %d b\n', ...
    nRho,nB);

fprintf('b    = [%.12f , %.12f]\n', ...
    paramB(1),paramB(end));

fprintf('rho  = [%.12f , %.12f]\n', ...
    paramRho(1),paramRho(end));

fprintf('db   = %.12e\n',db);
fprintf('drho = %.12e\n',drho);


[distB1,ibOne] = min(abs(paramB-1));

fprintf('Closest b to 1 = %.16f\n', ...
    paramB(ibOne));

fprintf('|b-1|          = %.3e\n', ...
    distB1);


[Bgrid,RHOgrid] = ...
    meshgrid(paramB,paramRho);


%% ========================================================================
% COMPONENT DEFINITIONS
%% ========================================================================

compNames = { ...
    'C1111', ...
    'C1122', ...
    'C1112', ...
    'C2222', ...
    'C2212', ...
    'C1212'};

compLabels = { ...
    '$C_{1111}$', ...
    '$C_{1122}$', ...
    '$C_{1112}$', ...
    '$C_{2222}$', ...
    '$C_{2212}$', ...
    '$C_{1212}$'};

compIds = { ...
    [1 1 1 1]
    [1 1 2 2]
    [1 1 1 2]
    [2 2 2 2]
    [2 2 1 2]
    [1 2 1 2]};

nComp = numel(compNames);


%% ========================================================================
% EXTRACT HOM SURFACES
%% ========================================================================

Yhom = zeros(nRho,nB,nComp);

for ic = 1:nComp

    id = compIds{ic};

    Yhom(:,:,ic) = squeeze( ...
        Chomog( ...
        id(1), ...
        id(2), ...
        id(3), ...
        id(4), ...
        :,:));

end


%% ========================================================================
% EVALUATE NN SURFACES
%% ========================================================================

fprintf('\nEvaluating NN surfaces...\n');

Ynn = zeros(nRho,nB,nComp);

bFlat   = Bgrid(:);
rhoFlat = RHOgrid(:);


for ic = 1:nComp

    id = compIds{ic};

    funNN = ...
        Interpolation.fun{ ...
        id(1), ...
        id(2), ...
        id(3), ...
        id(4)};

    values = ...
        funNN(bFlat,rhoFlat);

    Ynn(:,:,ic) = ...
        reshape(values,nRho,nB);

end

fprintf('NN surfaces evaluated.\n');


%% ========================================================================
% NN DERIVATIVES
%% ========================================================================

fprintf('Evaluating NN derivatives...\n');

dB_nn   = zeros(nRho,nB,nComp);
dRho_nn = zeros(nRho,nB,nComp);


for ic = 1:nComp

    id = compIds{ic};

    dfunNN = ...
        Interpolation.dfun{ ...
        id(1), ...
        id(2), ...
        id(3), ...
        id(4)};

    derivative = ...
        dfunNN(bFlat,rhoFlat);

    dB_nn(:,:,ic) = ...
        reshape( ...
        derivative{1}, ...
        nRho,nB);

    dRho_nn(:,:,ic) = ...
        reshape( ...
        derivative{2}, ...
        nRho,nB);

end

fprintf('NN derivatives evaluated.\n');


%% ========================================================================
% HOM DERIVATIVES - 5 POINT CENTRAL DIFFERENCE
%
%   f'(x_i) =
%
%   [f(i-2) - 8 f(i-1) + 8 f(i+1) - f(i+2)]
%   ------------------------------------------------
%                      12 h
%
%% ========================================================================

dB_hom   = nan(nRho,nB,nComp);
dRho_hom = nan(nRho,nB,nComp);


for ic = 1:nComp

    C = Yhom(:,:,ic);


    % --------------------------------------------------------------------
    % derivative with respect to b
    % --------------------------------------------------------------------

    dB_hom(:,3:end-2,ic) = ...
        ( ...
        C(:,1:end-4) ...
        - 8*C(:,2:end-3) ...
        + 8*C(:,4:end-1) ...
        - C(:,5:end) ...
        )/(12*db);


    % --------------------------------------------------------------------
    % derivative with respect to rho
    % --------------------------------------------------------------------

    dRho_hom(3:end-2,:,ic) = ...
        ( ...
        C(1:end-4,:) ...
        - 8*C(2:end-3,:) ...
        + 8*C(4:end-1,:) ...
        - C(5:end,:) ...
        )/(12*drho);

end


%% ========================================================================
% USEFUL DOMAIN MASK
%% ========================================================================

maskInterior = false(nRho,nB);

maskInterior(3:end-2,3:end-2) = true;


maskUseful = ...
    maskInterior & ...
    RHOgrid >= 0.10 & ...
    RHOgrid <= 0.90;


%% ========================================================================
% PRINT BASIC NN ERRORS
%% ========================================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf(' NN ERROR SUMMARY\n');
fprintf('============================================================\n');

fprintf('%9s %14s %14s %14s\n', ...
    'Comp', ...
    'Value', ...
    'd/db', ...
    'd/drho');


for ic = 1:nComp

    H = Yhom(:,:,ic);
    N = Ynn(:,:,ic);

    Hb = dB_hom(:,:,ic);
    Nb = dB_nn(:,:,ic);

    Hr = dRho_hom(:,:,ic);
    Nr = dRho_nn(:,:,ic);


    eValue = ...
        norm(N(maskUseful)-H(maskUseful)) / ...
        max(norm(H(maskUseful)),eps);


    eB = ...
        norm(Nb(maskUseful)-Hb(maskUseful)) / ...
        max(norm(Hb(maskUseful)),eps);


    eR = ...
        norm(Nr(maskUseful)-Hr(maskUseful)) / ...
        max(norm(Hr(maskUseful)),eps);


    fprintf('%9s %14.6e %14.6e %14.6e\n', ...
        compNames{ic}, ...
        eValue,eB,eR);

end


